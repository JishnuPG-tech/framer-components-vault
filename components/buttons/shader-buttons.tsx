const NAMED: Record<string, string> = {
    black: "#000000", white: "#ffffff", red: "#ff0000", green: "#008000", lime: "#00ff00", blue: "#0000ff", yellow: "#ffff00",
    cyan: "#00ffff", aqua: "#00ffff", magenta: "#ff00ff", fuchsia: "#ff00ff", orange: "#ffa500", purple: "#800080", pink: "#ffc0cb",
    gray: "#808080", grey: "#808080", silver: "#c0c0c0", navy: "#000080", teal: "#008080", maroon: "#800000", olive: "#808000",
}
const toLin = (c: number) => (c <= 0.04045 ? c / 12.92 : Math.pow((c + 0.055) / 1.055, 2.4))
const toGam = (c: number) => (c <= 0.0031308 ? 12.92 * c : 1.055 * Math.pow(c, 1 / 2.4) - 0.055)
const clamp01 = (x: number) => Math.min(Math.max(x, 0), 1)
const numPct = (x: string, pct: number) => (x.endsWith("%") ? (parseFloat(x) / 100) * pct : parseFloat(x))
function hsl2rgb(h: number, s: number, l: number): number[] {
    const k = (n: number) => (n + h / 30) % 12,
        a = s * Math.min(l, 1 - l)
    return [0, 8, 4].map((n) => l - a * Math.max(-1, Math.min(k(n) - 3, 9 - k(n), 1)))
}
/**
 * Colour -> [r, g, b] sRGB 0..1, or null. '#rgb' '#rgba' '#rrggbb' '#rrggbbaa', rgb()/rgba() (comma or space syntax, %, / alpha),
 * hsl()/hsla(), color(srgb | srgb-linear | display-p3 r g b), var(--token, fallback) (Framer colour styles), a few names,
 * [r, g, b] (0..1, or 0..255 when a channel is > 1). Alpha is ignored.
 */
function parseColor(c: unknown): number[] | null {
    if (Array.isArray(c) || ArrayBuffer.isView(c)) {
        const v = Array.from(c as ArrayLike<unknown>)
            .slice(0, 3)
            .map(Number)
        if (v.length < 3 || !v.every(Number.isFinite)) return null
        const k = Math.max(v[0], v[1], v[2]) > 1 ? 255 : 1
        return v.map((x) => clamp01(x / k))
    }
    if (typeof c !== "string") return null
    let s = c.trim().toLowerCase()
    if (s.startsWith("var(")) {
        const i = s.indexOf(","),
            j = s.lastIndexOf(")")
        return i > 0 && j > i ? parseColor(s.slice(i + 1, j)) : null
    }
    s = NAMED[s] || s
    let v: number[] | null = null
    if (s[0] === "#") {
        const h = s.slice(1)
        if (!/^[0-9a-f]+$/.test(h)) return null
        if (h.length === 3 || h.length === 4) v = [0, 1, 2].map((i) => parseInt(h[i] + h[i], 16) / 255)
        else if (h.length === 6 || h.length === 8) v = [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16) / 255)
    } else {
        const m = /^(rgba?|hsla?|color)\(([^()]*)\)$/.exec(s)
        if (!m) return null
        const q = m[2].replace(/\//g, " ").split(/[\s,]+/).filter(Boolean)
        if (m[1].startsWith("rgb") && q.length >= 3) v = q.slice(0, 3).map((x) => numPct(x, 255) / 255)
        else if (m[1].startsWith("hsl") && q.length >= 3) {
            const h = q[0].endsWith("turn")
                ? parseFloat(q[0]) * 360
                : q[0].endsWith("rad")
                  ? (parseFloat(q[0]) * 180) / Math.PI
                  : parseFloat(q[0])
            v = hsl2rgb(
                ((h % 360) + 360) % 360,
                clamp01(numPct(q[1], 1) / (q[1].endsWith("%") ? 1 : 100)),
                clamp01(numPct(q[2], 1) / (q[2].endsWith("%") ? 1 : 100))
            )
        } else if (m[1] === "color" && q.length >= 4) {
            const x = q.slice(1, 4).map((y) => numPct(y, 1))
            if (q[0] === "srgb") v = x
            else if (q[0] === "srgb-linear") v = x.map((y) => toGam(clamp01(y)))
            else if (q[0] === "display-p3") {
                // P3 -> sRGB (linear, D65), clipped
                const l = x.map((y) => toLin(clamp01(y)))
                v = [
                    1.2249401 * l[0] - 0.2249404 * l[1],
                    -0.0420569 * l[0] + 1.0420571 * l[1],
                    -0.0196376 * l[0] - 0.0786361 * l[1] + 1.0982735 * l[2],
                ].map((y) => toGam(clamp01(y)))
            }
        }
    }
    return v && v.every(Number.isFinite) ? v.map(clamp01) : null
}
function oklab(rgb: number[]): number[] {
    const [r, g, b] = rgb.map(toLin)
    const l = Math.cbrt(0.4122214708 * r + 0.5363325363 * g + 0.0514459929 * b),
        m = Math.cbrt(0.2119034982 * r + 0.6806995451 * g + 0.1073969566 * b)
    const s = Math.cbrt(0.0883024619 * r + 0.2817188376 * g + 0.6299787005 * b)
    return [
        0.2104542553 * l + 0.793617785 * m - 0.0040720468 * s,
        1.9779984951 * l - 2.428592205 * m + 0.4505937099 * s,
        0.0259040371 * l + 0.7827717662 * m - 0.808675766 * s,
    ]
}
function linOf(lab: number[]): number[] {
    // OKLab -> linear sRGB, unclamped
    const l = (lab[0] + 0.3963377774 * lab[1] + 0.2158037573 * lab[2]) ** 3,
        m = (lab[0] - 0.1055613458 * lab[1] - 0.0638541728 * lab[2]) ** 3
    const s = (lab[0] - 0.0894841775 * lab[1] - 1.291485548 * lab[2]) ** 3
    return [
        4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s,
        -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s,
        -0.0041960863 * l - 0.7034186147 * m + 1.707614701 * s,
    ]
}
const srgb = (lab: number[]) => linOf(lab).map((x) => clamp01(toGam(clamp01(x))))
function limit(rgb: number[], lmin: number, cmax: number): number[] {
    // clamp in OKLCH: L floor, chroma ceiling
    const [L, a, b] = oklab(rgb),
        C = Math.hypot(a, b),
        k = C > cmax ? cmax / C : 1
    return srgb([Math.max(L, lmin), a * k, b * k])
}
function warmTint(rgb: number[]): number[] {
    // C0: neutral-warm light tint, max channel 1, hue 40-100 deg, C <= 0.06
    const [, a, b] = oklab(rgb),
        C0 = Math.hypot(a, b)
    if (C0 < 0.01) return [1, 1, 1]
    let h = ((Math.atan2(b, a) * 180) / Math.PI + 360) % 360
    if (h < 40 || h > 100) h = Math.abs(((h - 40 + 540) % 360) - 180) <= Math.abs(((h - 100 + 540) % 360) - 180) ? 40 : 100
    const C = Math.min(C0, 0.06),
        ca = C * Math.cos((h * Math.PI) / 180),
        cb = C * Math.sin((h * Math.PI) / 180)
    let lo = 0.3,
        hi = 1.3
    for (let i = 0; i < 40; i++) {
        const L = 0.5 * (lo + hi)
        if (Math.max(...linOf([L, ca, cb])) > 1) hi = L
        else lo = L
    }
    return srgb([lo, ca, cb])
}
function ramp(fill: number[], deep: number[], mid: number[] | null, n: number): number[][] {
    // n stops fill -> (mid at 3/8) -> deep, piecewise linear in OKLab
    const a = oklab(fill),
        b = oklab(deep),
        m = mid ? oklab(mid) : null,
        tm = 3 / 8
    return Array.from({ length: n }, (_, i) => {
        const t = i / (n - 1)
        const lab = !m
            ? a.map((x, k) => x + (b[k] - x) * t)
            : t <= tm
              ? a.map((x, k) => x + ((m[k] - x) * t) / tm)
              : m.map((x, k) => x + ((b[k] - x) * (t - tm)) / (1 - tm))
        return [...srgb(lab), t]
    })
}
const CUSTOM_BASE: Record<string, string> = {
    "wind.add2": "#212023", "wind.cycleAdd": "#212023", "aurora.band2": "#212023", "tides.dark": "#212023",
    "wind.ramp": "#F6F5F8", "aurora.ramp": "#F6F5F8",
}
/**
 * Uniforms that replace the preset's colours. look = preset id ('A2') or 'family.look'. An unreadable colour keeps the
 * preset's. A0 top / bottom ray; A2, D2 top / middle / bottom band; D0 top / bottom band; ramps (A1, D1) deepest / mid colour;
 * C0 light tint; C1, C2 the R / B copy; B keeps its hue cycle (only the fill changes).
 */
function customUniforms(look: string, colors: CustomColors = NO_OPTS as CustomColors): CustomOut {
    const { fill, c1, c2, c3 } = colors
    const PR = (SB_PRESETS as Record<string, Preset | undefined>)[look]
    const key = PR ? PR.family + "." + PR.look : look
    const base = PR ? PR.fill : CUSTOM_BASE[key] || "#FFFFFF"
    const F = ((fill != null && parseColor(fill)) || parseColor(base)) as number[],
        out: CustomOut = { uFill: F }
    const k1 = c1 != null ? parseColor(c1) : null,
        k2 = c2 != null ? parseColor(c2) : null,
        k3 = c3 != null ? parseColor(c3) : null
    const L = (c: number[]) => limit(c, 0.71, 0.17)
    switch (key) {
        case "wind.add2": {
            // ray directions: colour at w = 1 is c (brightened to max channel 1)
            const dir = (v: number[]) => {
                const mx = Math.max(...v, 1e-6)
                return v.map((x, k) => Math.max(x / mx - F[k], 0))
            }
            if (k1) out.uC0 = dir(k1)
            if (k2) out.uC1 = dir(k2)
            break
        }
        case "wind.ramp": {
            // 9 stops fill -> (c2) -> c1, + 10th stop (c1 with C x 1.1) at 1.12
            if (!k1) break
            const deep = L(k1),
                lab = oklab(deep),
                top = limit(srgb([lab[0], lab[1] * 1.1, lab[2] * 1.1]), 0.71, 0.17)
            out.uLut = [...ramp(F, deep, k2 ? L(k2) : null, 9), [...top, 1.12]]
            break
        }
        case "aurora.ramp": // 9 stops fill -> (c2) -> c1
            if (k1) out.uLut = ramp(F, L(k1), k2 ? L(k2) : null, 9)
            break
        case "wind.band3":
        case "aurora.band3":
            if (k1) out.uC0 = L(k1)
            if (k2) out.uC1 = L(k2)
            if (k3) out.uC2 = L(k3)
            break
        case "aurora.band2": // dark alpha bands: any colour (may darken channels)
            if (k1) out.uC0 = k1
            if (k2) out.uC1 = k2
            break
        case "tides.dark": {
            // light = (1 - fill) x neutral-warm tint (max channel 1)
            const t = k1 ? warmTint(k1) : [1, 1, 1]
            out.uLight = F.map((x, k) => (1 - x) * t[k])
            break
        }
        case "tides.white":
            if (k1) out.uWa = limit(k1, 0.7, 0.1)
            if (k2) out.uWb = limit(k2, 0.7, 0.1)
            break
        default: // wind.cycleAdd / wind.cycleInk: hue cycle kept
    }
    return out
}

