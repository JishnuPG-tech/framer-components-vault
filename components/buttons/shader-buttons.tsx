/** CSS gradient layers (top first) for a W x H px pill; opts approximate the shader controls (scale, reach, gain). */
function staticLayers(entry: StaticEntry, W: number, H: number, opts: StaticOpts = {}): string[] {
    const sc = pn(opts.scale) > 0 ? pn(opts.scale) : 1,
        re = pn(opts.reach) > 0 ? pn(opts.reach) : 1,
        g = pn(opts.gain) > 0 ? pn(opts.gain) : 1
    return entry.layers.map((L) => {
        const rx = Math.max(L.rx_H * sc * re * H, 0.01),
            ry = Math.max(L.ry_H * sc * H, 0.01)
        const x = W - L.cx_from_right_H * sc * re * H,
            y = (0.5 + (L.cy_H - 0.5) * sc) * H
        const stops = g === 1 ? L.stops : L.stops.map(([c, p]): [string, number] => [scaleAlpha(c, g), p])
        return `radial-gradient(${f2(rx)}px ${f2(ry)}px at ${f2(x)}px ${f2(y)}px, ${stops.map(([c, p]) => `${c} ${f2(p)}%`).join(", ")})`
    })
}
function scaleAlpha(c: string, g: number): string {
    const m = /^rgba\((\d+), (\d+), (\d+), ([\d.]+)\)$/.exec(c)
    return m ? `rgba(${m[1]}, ${m[2]}, ${m[3]}, ${Math.round(clamp01(+m[4] * g) * 1000) / 1000})` : c
}
/** Full CSS background value: the layers plus the fill colour as the bottom layer (opts.fill === false: layers only). */
function staticBackground(entry: StaticEntry, W: number, H: number, opts: StaticOpts = {}): string {
    const l = staticLayers(entry, W, H, opts)
    return opts.fill === false ? l.join(", ") : l.concat(entry.fill).join(", ")
}
const toLinS = (c: number) => (c <= 0.04045 ? c / 12.92 : Math.pow((Math.max(c, 0) + 0.055) / 1.055, 2.4))
const toGamS = (c: number) => {
    c = clamp01(c)
    return c <= 0.0031308 ? 12.92 * c : 1.055 * Math.pow(c, 1 / 2.4) - 0.055
}
function oklabS(rgb: number[]): number[] {
    const [r, g, b] = rgb.map(toLinS)
    const l = Math.cbrt(Math.max(0.4122214708 * r + 0.5363325363 * g + 0.0514459929 * b, 0))
    const m = Math.cbrt(Math.max(0.2119034982 * r + 0.6806995451 * g + 0.1073969566 * b, 0))
    const s = Math.cbrt(Math.max(0.0883024619 * r + 0.2817188376 * g + 0.6299787005 * b, 0))
    return [
        0.2104542553 * l + 0.793617785 * m - 0.0040720468 * s,
        1.9779984951 * l - 2.428592205 * m + 0.4505937099 * s,
        0.0259040371 * l + 0.7827717662 * m - 0.808675766 * s,
    ]
}
function fromLab(c: number[]): number[] {
    const l = (c[0] + 0.3963377774 * c[1] + 0.2158037573 * c[2]) ** 3,
        m = (c[0] - 0.1055613458 * c[1] - 0.0638541728 * c[2]) ** 3
    const s = (c[0] - 0.0894841775 * c[1] - 1.291485548 * c[2]) ** 3
    return [
        4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s,
        -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s,
        -0.0041960863 * l - 0.7034186147 * m + 1.707614701 * s,
    ].map((x) => toGamS(clamp01(x)))
}
const mix3 = (a: number[], b: number[], t: number) => a.map((x, i) => x + (b[i] - x) * t)
const sstep = (a: number, b: number, x: number) => {
    const t = clamp01((x - a) / (b - a))
    return t * t * (3 - 2 * t)
}
function rampLut(lut: number[][], F: number[], x: number): number[] {
    let c = F.slice()
    for (let i = 0; i < lut.length - 1; i++)
        c = mix3(c, lut[i + 1], clamp01((x - lut[i][3]) / Math.max(lut[i + 1][3] - lut[i][3], 1e-4)))
    return c
}
/** B hue cycle (12 circular stops), phase x 0..1. */
function cycleLut(pal: number[][], x: number): number[] {
    x = x - Math.floor(x)
    if (x < pal[0][3]) x += 1
    let c = pal[0].slice(0, 3)
    for (let i = 0; i < 11; i++) c = mix3(c, pal[i + 1], clamp01((x - pal[i][3]) / Math.max(pal[i + 1][3] - pal[i][3], 1e-4)))
    return mix3(c, pal[0], clamp01((x - pal[11][3]) / Math.max(pal[0][3] + 1 - pal[11][3], 1e-4)))
}
/** Colour of a look at (role, k); key 'family.look', U = colour uniforms, tint (B only). Same formulas as the shader. */
function lookColour(key: string, U: Uniforms, role: number, k: number, tint: number[] | null): number[] {
    const F = vecU(U, "uFill")
    switch (key) {
        case "wind.add2": {
            const m = role,
                p = vecU(U, "uXf")[3],
                gt = vecU(U, "uRay")[0] * Math.pow(1 - m, p),
                gb = vecU(U, "uRay")[1] * Math.pow(m, p)
            const col = F.map((f, i) => Math.min(f + k * (gt * vecU(U, "uC0")[i] + gb * vecU(U, "uC1")[i]), 1))
            const pb = vecU(U, "uRay")[2] > 0 ? vecU(U, "uRay")[2] : 1
            const hot =
                Math.min(vecU(U, "uHot")[0] * (1 + vecU(U, "uHot")[3] * Math.pow(4 * m * (1 - m), pb)), 1) *
                sstep(vecU(U, "uHot")[1], vecU(U, "uHot")[2], k)
            // tinted hot core (final2 A0 cream: uHotC; absent / all 0 = white, the restored proto/final A0), never darkens
            const hotC = U["uHotC"] as number[] | undefined
            const hc = hotC && hotC[0] + hotC[1] + hotC[2] > 0 ? hotC : [1, 1, 1]
            return col.map((c, i) => c + (Math.max(hc[i], c) - c) * hot)
        }
        case "wind.ramp":
        case "aurora.ramp":
            return rampLut(matU(U, "uLut"), F, k)
        case "wind.band3": {
            const e1 = clamp01(role),
                e2 = clamp01(role - 1)
            return fromLab(mix3(mix3(oklabS(vecU(U, "uC0")), oklabS(vecU(U, "uC1")), e1), oklabS(vecU(U, "uC2")), e2))
        }
        case "aurora.band2":
            return mix3(vecU(U, "uC0"), vecU(U, "uC1"), role)
        case "aurora.band3": {
            const e1 = clamp01(role),
                e2 = clamp01(role - 1)
            return mix3(mix3(vecU(U, "uC0"), vecU(U, "uC1"), e1), vecU(U, "uC2"), e2)
        }
        case "wind.cycleAdd": {
            const T = tint as number[]
            return F.map((f, i) => Math.min(f + (1 - f) * k * T[i], 1))
        }
        case "wind.cycleInk": {
            const T = tint as number[],
                ink4 = vecU(U, "uInk"),
                kref = vecU(U, "uKref"),
                inkK = vecU(U, "uInkK")
            const u0 = ink4[3]
            const E = T.map((t, i) => {
                const u = k * t,
                    uk = u0 < 0.999 ? (u >= u0 ? u0 + (1 - u0) * (1 - Math.exp(-(u - u0) / (1 - u0))) : u) : Math.min(u, 1)
                return (1 - kref[i]) * uk
            })
            const Am = (E[0] + E[1] + E[2]) / 3,
                ink = ink4[0] * (1 - Math.exp(-Am / ink4[1]))
            return F.map((f, i) => clamp01(f - ink * inkK[i] + ink4[2] * (E[i] - Am)))
        }
        case "tides.dark": {
            const s = role,
                w = s < 0 ? [1, 1 + s, 1 + s] : [1 - s, 1 - s, 1]
            const Li = vecU(U, "uLight"),
                Ka = vecU(U, "uKa"),
                Kb = vecU(U, "uKb"),
                Kl = vecU(U, "uKl")
            return F.map((f, i) => {
                const T = k * w[i]
                return Math.min(f + Li[i] * (Ka[i] + Kb[i] * Math.exp(-T / Math.max(Kl[i], 1e-3))) * T, 1)
            })
        }
        case "tides.white": {
            const s = role,
                Wx = vecU(U, "uWx"),
                Wa = vecU(U, "uWa"),
                Wb = vecU(U, "uWb")
            const aR = 1 - Math.exp((-k * (1 - Math.max(s, 0))) / Math.max(Wx[0], 1e-3)),
                aB = 1 - Math.exp((-k * (1 + Math.min(s, 0))) / Math.max(Wx[1], 1e-3))
            return F.map((f, i) => f + aR * (Wa[i] - f) * (1 - Wx[2] * aB) + aB * (Wb[i] - f))
        }
    }
    throw new Error("unknown look " + key)
}
/**
 * Entry with the stop colours re-derived from colour uniforms (e.g. customUniforms(...)); idOrLook = preset id or
 * 'family.look'. Fed the preset's own uniforms it returns the preset's stored stops.
 */
function customStatic(idOrLook: string, uniforms: Record<string, unknown> | null = {}, opts: { palettePhase?: number } = {}): StaticEntry {
    const ST = SB_STATIC as Record<string, StaticEntry | undefined>
    const base = ST[idOrLook] || ST[LOOK_PRESET[idOrLook]]
    if (!base) throw new Error("unknown preset / look " + idOrLook)
    const U: Uniforms = Object.assign({}, base.model)
    for (const [k, v] of Object.entries(uniforms || {}))
        if (v != null)
            U[k] = (
                Array.isArray(v) || ArrayBuffer.isView(v)
                    ? Array.from(v as ArrayLike<unknown>, (x) =>
                          Array.isArray(x) || ArrayBuffer.isView(x) ? Array.from(x as ArrayLike<number>) : pn(x)
                      )
                    : v
            ) as UniformValue
    const tint = base.look.startsWith("wind.cycle") ? cycleLut(matU(U, "uPal"), (base.tintPhase as number) + (pn(opts.palettePhase) || 0)) : null
    return Object.assign({}, base, {
        fill: hexS(vecU(U, "uFill")),
        model: U,
        layers: base.layers.map((L) =>
            Object.assign({}, L, {
                stops: L.src.map(([k, a, p, role]): [string, number] => [rgbaS(lookColour(base.look, U, role, k, tint), a), p]),
            })
        ),
    })
}
