/** The noise needs fragment highp (fp32); mediump (fp16) GPUs get the CSS fallback. */
function supported(gl: WebGLRenderingContext | WebGL2RenderingContext): boolean {
    try {
        const f = gl.getShaderPrecisionFormat(gl.FRAGMENT_SHADER, gl.HIGH_FLOAT)
        return !!f && f.precision >= 23 && gl.getParameter(gl.MAX_FRAGMENT_UNIFORM_VECTORS) >= 40
    } catch (e) {
        return false
    }
}

const frameCache: Partial<Record<PresetId, FrameState>> = {}
/** One per-frame uniform object per instance; typed arrays are reused, nothing is allocated per frame. */
function createFrameUniforms(id: PresetId): FrameState {
    const P = SB_PRESETS[id]
    const o: FrameState = { uScale: 1, uGain: 1, uReach: 1, uBoost: 0, uGuard: 0, uDither: 0 }
    const r = o as unknown as Record<string, F4>
    const names = { wind: ["uW0", "uW1", "uW2", "uW3", "uW6"], aurora: ["uA0", "uA1"], tides: TIDES_S.concat(["uS6"]) }[P.family]
    for (const n of names) r[n] = new Float32Array(4)
    if (P.family === "wind" && (P.look === "add2" || P.look === "band3")) o.uW4 = new Float32Array(4)
    if (P.family === "wind" && P.state.pulse) o.uW5 = new Float32Array(4)
    return o
}
const SEED_WIND = [37, 11, 0],
    SEED_AURORA = [37, 101, 59],
    seedTmp = [0, 0, 0]
const TIDES_S = ["uS0", "uS1", "uS2", "uS3", "uS4", "uS5"]
const PHI = 0.6180339887498949,
    SEED_T = { wind: 1000, aurora: 1000, tides: LOOP }
function seedVec(seed: unknown, k: number[]): number[] {
    // number -> lattice offset k * seed (reused array); [x, y, z] -> as given
    if (Array.isArray(seed)) {
        for (let i = 0; i < 3; i++) seedTmp[i] = pn(seed[i]) || 0
        return seedTmp
    }
    const s = pn(seed) || 0
    seedTmp[0] = k[0] * s
    seedTmp[1] = k[1] * s
    seedTmp[2] = k[2] * s
    return seedTmp
}
// seed -> clock offset: number -> fract(seed phi) T (T 1000 s; tides: the 4 pi loop); [x, y, z, dt] -> dt s. Seed 0 = reference clock.
function seedTime(seed: unknown, fam: "wind" | "aurora" | "tides"): number {
    if (Array.isArray(seed)) return pn(seed[3]) || 0
    const f = (pn(seed) || 0) * PHI
    return (f - Math.floor(f)) * SEED_T[fam]
}
const vecU = (U: Uniforms, k: string) => U[k] as number[]
const matU = (U: Uniforms, k: string) => U[k] as number[][]

// wind field (A, B): cross-fade of two rigidly advected layers, bend, procession, band boundaries
function windState(P: WindPreset, t: number, sc: number, seed: number[], opts: FrameOpts, o: FrameState) {
    const S = P.state,
        U = P.uniforms,
        C = opts.clip && P.clip ? P.clip : S // clip: reference-clip clock (validation)
    const period = C.period,
        phase = C.phase
    const th = wrap((TAU / period) * t, TAU) + phase
    const ux = S.U[0],
        uy = S.U[1],
        ax = S.latA[0] / sc,
        ay = S.latA[1] / sc,
        bx = S.latB[0] / sc,
        by = S.latB[1] / sc
    set4(o.uW0 as F4, ax, ay, wrap(ax * ux * t - seed[0], 6400), wrap(ay * uy * t - seed[1], 256))
    set4(o.uW2 as F4, bx, by, wrap(bx * ux * t - seed[0], 6400), wrap(by * uy * t - seed[1], 256))
    const e = 0.5 + 0.5 * Math.sin(th - (S.lag || 0)) // streaky share, lagging the bend by S.lag; mix 1..2 = linear .. smoothstep
    set4(
        o.uW1 as F4,
        S.Kb * Math.sin(th - 2.75) * sc,
        wrap(S.omega * t + seed[2], 1280),
        wrap((vecU(U, "uProc")[1] / sc) * S.procV * t, TAU),
        e + (e * e * (3 - 2 * e) - e) * (S.mix - 1)
    )
    if (S.ring) {
        // ring layer: radial phase, rotation, evolution (+ seed), seamless wraps; without state.ring uW6 stays 0 (uRingK.x = 0: unused)
        const R = S.ring,
            ev = R[2] * t
        set4(
            o.uW6 as F4,
            wrap((vecU(U, "uRingK")[0] / sc) * R[0] * t, 1280),
            wrap(R[1] * t, TAU),
            wrap(0.6 * ev + seed[0], 1280),
            wrap(0.8 * ev + seed[1], 256)
        )
    }
    const ks = vecU(U, "uProc2")[0] / sc
    set4(o.uW3 as F4, wrap(ks * ux * t, 6400), wrap(ks * uy * t, 256), wrap(S.procOmega * t, 1280), band(S.b1, t))
    if (o.uW4) {
        const kx = vecU(U, "uHueW")[1] / sc,
            ky = vecU(U, "uHueW")[2] / sc
        set4(o.uW4, wrap(kx * ux * t, 6400), wrap(ky * uy * t, 256), wrap(S.warpOmega * t, 1280), band(S.b2, t))
    }
    if (o.uW5 && S.pulse) {
        // B: breathing pulse, period pi, + phase-locked palette
        const B = S.pulse,
            ph = wrap(t - B.t0, Math.PI)
        const s = Math.max(Math.sin(ph - B.skew * Math.sin(ph)), 1e-6)
        const sr = (Math.sqrt(s * s + 0.0025) - 0.05) / 0.9512492197250393 // C1 at the trough: the reach eases
        set4(
            o.uW5,
            B.k0 + (1 - B.k0) * Math.pow(s, B.qk),
            B.r0 + (1 - B.r0) * Math.pow(sr, B.qr),
            wrap(ph / Math.PI + B.offset + (pn(opts.palettePhase) || 0), 1),
            s
        )
    }
}

// aurora field (D): right-anchored noise, swing (+ moving body, evaluated from s in the shader), band boundaries, loop pulse
function auroraState(P: AuroraPreset, t: number, seed: number[], o: FrameState) {
    const S = P.state,
        th = wrap((TAU / S.period) * t, TAU) + S.phase
    set4(
        o.uA0 as F4,
        wrap(seed[0], 6400),
        wrap(seed[1] - vecU(P.uniforms, "uLat")[1] * S.drift * t, 6400),
        wrap(S.omega * t + seed[2], 1280),
        Math.sin(th)
    )
    set4(o.uA1 as F4, band(S.b1, t), S.b2 ? band(S.b2, t) : 0, band(S.tilt, t), Math.cos(th - (S.pulsePhase || 0)))
}

// tides (C): 24 track parameters, Fourier series K = 8 in theta = (t mod 4 pi) / 2 (exact 4 pi loop); two track sets (V4 / v1)
const cosK = new Float64Array(9),
    sinK = new Float64Array(9)
const smoothD = (a: number, b: number, x: number) => {
    const u = Math.min(Math.max((x - a) / (b - a), 0), 1)
    return u * u * (3 - 2 * u)
}
function tidesState(P: TidesPreset, t: number, o: FrameState) {
    const th = 0.5 * wrap(t, LOOP),
        v1 = P.state.tracks === "v1" // v1: proto/final tracks (settle round), else the V4 refit
    const q = vecU(P.uniforms, "uTq"),
        r = vecU(P.uniforms, "uTr"),
        dth = th - r[0] // cap streak: von Mises window around theta0, exactly 0 outside
    const e = Math.exp(r[1] * (Math.cos(dth) - 1))
    set4(o.uS6 as F4, e * smoothD(0.01, 0.03, e), q[1] + q[2] * Math.sin(dth), 0, 0)
    for (let k = 1; k < 9; k++) {
        cosK[k] = Math.cos(k * th)
        sinK[k] = Math.sin(k * th)
    }
    const ro = o as unknown as Record<string, F4>
    for (let j = 0; j < 6; j++) {
        const v = ro[TIDES_S[j]],
            A = v1 ? SB_TIDES_A1[j] : SB_TIDES_A[j],
            B = v1 ? SB_TIDES_B1[j] : SB_TIDES_B[j]
        for (let c = 0; c < 4; c++) {
            let s = A[0][c]
            for (let k = 1; k < A.length; k++) s += A[k][c] * cosK[k] + B[k][c] * sinK[k]
            v[c] = s
        }
    }
}

/**
 * Every uniform that can change per frame: the clock state + the controls. opts: scale / gain / reach (unset = 1), boost (hover
 * 0..1), guard (text end in H, 0 = off), aspect (W/H: guard >= 0.3 H), dither (1/255), seed (number or [x, y, z, dt]),
 * palettePhase (B), clip (validation only). out: the instance's object from createFrameUniforms(id).
 */
function frameUniforms(id: PresetId, t: number, opts: FrameOpts = NO_OPTS, out?: FrameState): FrameState {
    const P = SB_PRESETS[id],
        o = out || frameCache[id] || (frameCache[id] = createFrameUniforms(id))
    const sc = ctl(opts.scale, RANGE.scale)
    o.uScale = sc
    o.uGain = ctl(opts.gain, RANGE.gain)
    o.uReach = ctl(opts.reach, RANGE.reach)
    o.uBoost = Math.min(Math.max(pn(opts.boost) || 0, 0), 1)
    const g = Math.max(pn(opts.guard) || 0, 0)
    o.uGuard = pn(opts.aspect) > 0 ? Math.max(g, GUARD_MIN) : g
    o.uDither = Math.max(pn(opts.dither) || 0, 0)
    const ts = t + seedTime(opts.seed, P.family)
    if (P.family === "wind") windState(P, ts, sc, seedVec(opts.seed, SEED_WIND), opts, o)
    else if (P.family === "aurora") auroraState(P, ts, seedVec(opts.seed, SEED_AURORA), o)
    else tidesState(P, ts, o)
    return o
}

