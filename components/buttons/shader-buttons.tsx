/** Icon paths on a 24 x 24 grid (stroked with currentColor, round ends); dot is a filled disc. */
const GLYPH_PATHS: Record<Exclude<GlyphKind, "none" | "dot">, string> = {
    arrow: "M5 12h14M13 6l6 6-6 6",
    arrowUpRight: "M7 17 17 7M8.5 7H17v8.5",
    chevron: "M9.5 6l6 6-6 6",
    plus: "M12 5v14M5 12h14",
    check: "M5 12.5l4.5 4.5L19 7.5",
}
function Glyph({ kind, size, stroke }: { kind: GlyphKind; size: number; stroke: number }) {
    if (kind === "none") return null
    const sw = (stroke * 24) / size
    return (
        <svg className="sb-gi" width={size} height={size} viewBox="0 0 24 24" fill="none" aria-hidden="true" focusable="false">
            {kind === "dot" ? (
                <circle cx="12" cy="12" r="5.5" fill="currentColor" />
            ) : (
                <path d={GLYPH_PATHS[kind]} stroke="currentColor" strokeWidth={sw} strokeLinecap="round" strokeLinejoin="round" />
            )}
        </svg>
    )
}

/** Hover motion of the icon (pointer hover and keyboard focus): arrows move along their direction, plus turns, dot grows. */
function glyphMotion(kind: GlyphKind, shift: number): string {
    if (shift <= 0) return ""
    const s = fq(shift)
    if (kind === "arrowUpRight") return `translate(${fq(shift * 0.75)}px,-${fq(shift * 0.75)}px)`
    if (kind === "plus") return "rotate(90deg)"
    if (kind === "dot" || kind === "check") return `scale(${fq(1 + shift / 16)})`
    return `translateX(${s}px)`
}

/** Mouse / pen enter or move: the pointer position in the button box (0..1, scale-independent); touch has no hover. */
function pointerTo(e: React.PointerEvent, kind: "ptr" | "move", onHover: NonNullable<ViewArgs["onHover"]>) {
    if (e.pointerType === "touch") return
    const r = (e.currentTarget as HTMLElement).getBoundingClientRect()
    onHover(kind, 1, r.width > 0 ? (e.clientX - r.left) / r.width : 0.5, r.height > 0 ? (e.clientY - r.top) / r.height : 0.5)
}

/** v7: text-guard mask stops [f, alpha] of the stand-in, alpha = smoothstep(f) at 17 evenly spaced f (the shader's ramp). */
