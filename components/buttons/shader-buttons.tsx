// controls: unset / invalid (<= 0, NaN, non-numeric) = neutral 1 (as the shader's ctl()), else clamped to the documented range
const RANGE = { scale: [0.8, 1.25], gain: [0.75, 1.3], reach: [0.8, 1.25] }
const ctl = (x: unknown, r: number[]) => {
    const v = pn(x)
    return v > 0 ? Math.min(Math.max(v, r[0]), r[1]) : 1
}
const GUARD_MIN = 0.3 // with opts.aspect: the glow fades out before the left cap

/** Canvas span in H from the right end that the preset needs (any hover); capped at aspect = W/H when given. */
