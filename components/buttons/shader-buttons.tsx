/** Brightest saturated colour of the look against its fill (score = OKLCH chroma x |L - L_fill|). */
function accentOf(P: Preset, id: PresetId, U: Uniforms, cols: CustomColors | null): string {
    const F = vecU(U, "uFill")
    let cands: number[][] = []
    if (P.family === "tides") {
        if (cols) cands = [cols.c1, P.look === "white" ? cols.c2 : null].map((c) => (c == null ? null : parseColor(c))).filter((c): c is number[] => !!c)
        if (!cands.length) return TIDES_ACCENT[id] ?? "#09FDC5"
    } else {
        const key = P.family + "." + P.look
        if (key === "wind.add2") {
            const ray = vecU(U, "uRay")
            cands = [vecU(U, "uC0").map((c, i) => Math.min(F[i] + ray[0] * c, 1)), vecU(U, "uC1").map((c, i) => Math.min(F[i] + ray[1] * c, 1))]
        } else if (key === "wind.ramp" || key === "aurora.ramp") cands = matU(U, "uLut").slice(1).map((s) => s.slice(0, 3))
        else if (key.startsWith("wind.cycle")) cands = matU(U, "uPal").map((s) => s.slice(0, 3))
        else cands = ["uC0", "uC1", "uC2"].filter((k) => k in U).map((k) => vecU(U, k))
    }
    const Lf = oklab(F)[0]
    let best = cands[0] ?? [1, 1, 1],
        score = -1
    for (const c of cands) {
        const [L, a, b] = oklab(c)
        const s = Math.hypot(a, b) * Math.abs(L - Lf)
        if (s > score) {
            score = s
            best = c
        }
    }
    return hexS(best)
}

function resolveLook(lookKey: unknown, colors: ColorsProps | undefined): Look {
    const L = LOOKS.find((l) => l.key === lookKey) ?? LOOKS[0]
    const id: PresetId = L.id
    const P = SB_PRESETS[id]
    const cols: CustomColors | null =
        colors && colors.custom === true
            ? {
                  fill: colors.fill ?? DEFAULT_CUSTOM.fill,
                  c1: colors.color1 ?? DEFAULT_CUSTOM.c1,
                  c2: colors.color2 ?? DEFAULT_CUSTOM.c2,
                  c3: colors.color3 ?? DEFAULT_CUSTOM.c3,
              }
            : null
    const cu = cols ? customUniforms(id, cols) : null
    const U: Uniforms = cu ? { ...P.uniforms, ...cu } : P.uniforms
    const consts: [string, number | Float32Array][] = Object.entries(U).map(([k, v]) => [
        k,
        typeof v === "number" ? v : new Float32Array((v as (number | number[])[]).flat() as number[]),
    ])
    const fill = vecU(U, "uFill")
    return {
        key: L.key,
        id,
        P,
        consts,
        constKey: id + (cols ? "|" + [cols.fill, cols.c1, cols.c2, cols.c3].join("|") : ""),
        fill,
        fillCss: hexS(fill),
        fillL: oklab(fill)[0],
        entry: cu ? customStatic(id, cu) : SB_STATIC[id],
        accent: accentOf(P, id, U, cols),
    }
}

function useLook(lookKey: unknown, c: ColorsProps | undefined): Look {
    const custom = !!c && c.custom === true
    return React.useMemo(
        () => resolveLook(lookKey, c),
        // eslint-disable-next-line react-hooks/exhaustive-deps
        [lookKey, custom, custom && c?.fill, custom && c?.color1, custom && c?.color2, custom && c?.color3]
    )
}

const COLOR_KEYS = ["fill", "color1", "color2", "color3"] as const
/**
 * Framer colour styles arrive as var(--token, fallback). Custom colours that use one are resolved to the token's live value
 * (light / dark), so the fill, the glow and the stand-in follow the style like the text colours do. Server markup and the
 * first render use the fallback; prefers-color-scheme changes resolve again.
 */
function useTokens(rootRef: React.MutableRefObject<HTMLElement | null>, colors: ColorsProps | undefined): ColorsProps | undefined {
    const on = !!colors && colors.custom === true
    const key = on ? COLOR_KEYS.map((k) => { const v = colors?.[k]; return typeof v === "string" && /^\s*var\(/i.test(v) ? v : "" }).join("|") : ""
    const [res, setRes] = React.useState<{ key: string; vals: string[] } | null>(null)
    useIsoLayoutEffect(() => {
        const el = rootRef.current
        if (!/var\(/i.test(key) || !el || typeof getComputedStyle !== "function") {
            setRes(null)
            return
        }
        const read = () => {
            const cs = getComputedStyle(el)
            const vals = key.split("|").map((v) => {
                const m = /^\s*var\(\s*(--[\w-]+)/i.exec(v)
                const live = m ? cs.getPropertyValue(m[1]).trim() : ""
                return live && parseColor(live) ? live : ""
            })
            setRes((p) => (p && p.key === key && p.vals.join("|") === vals.join("|") ? p : { key, vals }))
        }
        read()
        const mq = typeof window.matchMedia === "function" ? window.matchMedia("(prefers-color-scheme: dark)") : null
        if (!mq) return
        if (typeof mq.addEventListener === "function") mq.addEventListener("change", read)
        else mq.addListener(read)
        return () => {
            if (typeof mq.removeEventListener === "function") mq.removeEventListener("change", read)
            else mq.removeListener(read)
        }
    }, [key])
    if (!on || !res || res.key !== key || !colors) return colors
    const out: ColorsProps = { ...colors }
    COLOR_KEYS.forEach((k, i) => {
        if (res.vals[i]) out[k] = res.vals[i]
    })
    return out
}

/** Everything the layout of the content depends on, resolved once per render (render, estimate and measure share it). */
interface Content {
    title: string
    subtitle: string
    stacked: boolean
    /** resolved: Auto = away from the glow */
    align: Exclude<Align, "auto">
    side: Side
    titleUpper: boolean
    subUpper: boolean
    glyph: GlyphKind
    glyphPos: GlyphPos
    glyphSize: number
    glyphBox: number
    glyphGap: number
    circle: boolean
    showEq: boolean
    padding: string
}
function contentOf(props: Props, look: Look): Content {
    const text = props.text ?? {}
    const g = props.glyph ?? {}
    const stacked = text.layout === "stacked"
    const glyph = oneOf(g.kind, ["none", "arrow", "arrowUpRight", "chevron", "plus", "check", "dot"] as const, DEF.glyph)
    const glyphSize = clamp(numOr(g.size, DEF.glyphSize), 6, 64)
    const circle = g.circle === true
    const circleSize = Math.max(clamp(numOr(g.circleSize, DEF.circleSize), 12, 160), glyphSize)
    const mode = props.icon?.mode ?? "hide"
    const side: Side = props.effect?.side === "left" ? "left" : "right"
    const al = oneOf(text.align, ["auto", "left", "center", "right"] as const, "auto")
    // side Left mirrors the layout: padding left / right swap (the icon end follows the glow), Auto aligns away from the glow
    const pd = normPadding(props.padding, DEF.padding).split(" ")
    return {
        title: props.title ?? DEF.title,
        subtitle: stacked ? (props.subtitle ?? DEF.subtitle) : "",
        stacked,
        align: al === "auto" ? (side === "left" ? "right" : "left") : al,
        side,
        titleUpper: text.titleCase === "upper",
        subUpper: text.subtitleCase === "upper",
        glyph,
        glyphPos: g.position === "leading" ? "leading" : "trailing",
        glyphSize,
        glyphBox: glyph === "none" ? 0 : circle ? circleSize : glyphSize,
        glyphGap: clamp(numOr(g.gap, DEF.glyphGap), 0, 80),
        circle,
        showEq: mode === "show" || (mode === "auto" && look.P.family === "tides"),
        padding: side === "left" ? `${pd[0]} ${pd[3]} ${pd[2]} ${pd[1]}` : pd.join(" "),
    }
}

/** A length k x W + px (W = the pill width): the guard before measuring is known only in these terms (server markup). */
interface Len {
    k: number
    px: number
}
/**
 * Text guard before the text is measured (server markup, first render): the end of the text block on the glow side, from the
 * glow's far end (side Right: from the left edge; Left: from the right edge), from the strings at about 0.55 em per
 * character (0.64 em in capitals). A trailing icon sits over the glow and does not count; a leading one does.
 */
function estimateGuard(props: Props, c: Content): Len | null {
    const text = props.text ?? {}
    const ft = cssPx(text.titleFont?.fontSize, DEF.titleSize),
        fs = cssPx(text.subtitleFont?.fontSize, DEF.subtitleSize)
    const eq = c.showEq ? ((c.stacked ? c.subtitle : c.title) ? 0.73 : 0) + 1.062 : 0
    const wt = c.title ? c.title.length * (c.titleUpper ? 0.64 : 0.55) * ft + (!c.stacked ? eq * ft : 0) : 0
    const ws = c.subtitle ? c.subtitle.length * (c.subUpper ? 0.66 : 0.55) * fs + eq * fs : c.stacked && c.showEq ? eq * fs : 0
    const lead = c.glyphPos === "leading" && c.glyphBox ? c.glyphBox + (wt || ws ? c.glyphGap : 0) : 0
    const w = Math.max(wt, ws) + lead
    if (w <= 0) return null
    const pad = c.padding.split(" ")
    const icon = c.glyphPos === "trailing" && c.glyphBox ? c.glyphBox + c.glyphGap : 0
    const pl = cssPx(pad[3], 24) + (c.side === "left" ? icon : 0),
        pr = cssPx(pad[1], 12) + (c.side === "right" ? icon : 0)
    // left / right edge of the text block as k W + px
    const L: Len = c.align === "left" ? { k: 0, px: pl } : c.align === "right" ? { k: 1, px: -pr - w } : { k: 0.5, px: (pl - pr) / 2 - w / 2 }
    return c.side === "right" ? { k: L.k, px: L.px + w } : { k: 1 - L.k, px: -L.px }
}

/**
 * Drop shadow scaled to H: a soft lift plus a tight contact shadow, lighter on light fills; WebKit renders blur tighter, so it
 * gets blur x 1.19. The cq forms follow the pill's own height (also in the server markup); px forms for browsers without them.
 */
function autoShadow(H: number, fillL: number) {
    const a = fillL < 0.5 ? 0.42 : fillL < 0.985 ? 0.16 : 0.12
    const r = (x: number) => Math.round(x * 100) / 100
    const ac = Math.round(a * 0.45 * 1000) / 1000
    const mk = (u: (x: number) => string, k: number) =>
        `0 ${u(0.03)} ${u(0.06 * k)} 0 rgba(0,0,0,${ac}), 0 ${u(0.16)} ${u(0.4 * k)} ${u(-0.16)} rgba(0,0,0,${a})`
    const px = (x: number) => r(x * H) + "px",
        cq = (x: number) => fq(x * 100) + "cqh"
    return { base: mk(px, 1), webkit: mk(px, 1.19), baseCq: mk(cq, 1), webkitCq: mk(cq, 1.19) }
}

