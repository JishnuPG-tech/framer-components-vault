interface Size {
    w: number
    h: number
    /** text guard (end of the text block on the glow side, from the glow's far end) in H; 0 = no text */
    guard: number
    /** the same in px */
    gpx: number
    /** false until the first measurement (server markup, first render) */
    measured: boolean
}
const DEFAULT_GEOM: Size = { w: DEFAULT_SIZE.w, h: DEFAULT_SIZE.h, guard: 0, gpx: 0, measured: false }
/**
 * Measures the root and the text guard (root + every measured element observed: text lines and a leading icon; a trailing
 * icon sits over the glow and is left out). W and H are the fractional layout size (getComputedStyle, then the
 * ResizeObserver's content rect; the root has no padding or border), never rounded and unaffected by transforms such as the
 * canvas zoom, so the canvas always covers the whole pill. Side Right: guard = the right end of the block from the left
 * edge; side Left: the left end of the block from the right edge (the mirrored shader's coordinates).
 */
function useMeasure(rootRef: React.MutableRefObject<HTMLElement | null>, deps: unknown[], side: Side, onGeom?: (g: Size) => void): Size {
    const [size, setSize] = React.useState(DEFAULT_GEOM)
    useIsoLayoutEffect(() => {
        const el = rootRef.current
        if (!el) return
        const cs = getComputedStyle(el)
        let w = parseFloat(cs.width),
            h = parseFloat(cs.height)
        if (!(w >= 0)) w = el.offsetWidth
        if (!(h >= 0)) h = el.offsetHeight
        const read = () => {
            let r = 0,
                l = Infinity
            el.querySelectorAll<HTMLElement>(".sb-m").forEach((m) => {
                r = Math.max(r, m.offsetLeft + m.offsetWidth)
                l = Math.min(l, m.offsetLeft)
            })
            const gpx = r > 0 ? (side === "left" ? Math.max(w - l, 0) : r) : 0
            const g: Size = { w, h, guard: gpx > 0 && h > 0 ? gpx / h : 0, gpx, measured: true }
            if (onGeom) onGeom(g)
            setSize((s) => (s.measured && s.w === g.w && s.h === g.h && s.gpx === g.gpx ? s : g))
        }
        read()
        if (typeof ResizeObserver === "undefined") return
        const ro = new ResizeObserver((entries) => {
            for (const e of entries)
                if (e.target === el) {
                    w = e.contentRect.width
                    h = e.contentRect.height
                }
            read()
        })
        ro.observe(el)
        el.querySelectorAll(".sb-m").forEach((m) => ro.observe(m))
        return () => ro.disconnect()
        // eslint-disable-next-line react-hooks/exhaustive-deps
    }, deps)
    return size
}

/** Measure deps: whatever moves the measured elements without resizing them (the tag swaps the whole subtree). */
function measureDeps(props: Props, look: Look): unknown[] {
    const C = contentOf(props, look)
    return [tagKindOf(props), !!C.title, !!C.subtitle, C.stacked, C.showEq, C.padding, C.align, C.side, C.glyphPos, C.glyphBox, C.glyphGap]
}

// ---- v8: shader stills for the static renderer (Framer canvas, export, thumbnails) ----------------------------------------
/** One still: the live button's first frame at these settings, drawn at res device px per CSS px. */
interface StillJob {
    look: Look
    /** flow time (the look's stillTime, where every live button starts) */
    t: number
    W: number
    H: number
    guard: number
    scale: number
    reach: number
    gain: number
    side: Side
    seed: number
    res: number
}
/** A drawn still: its bitmap and its CSS size (the right end of the pill, the same span as the live canvas). */
interface StillOut {
    cv: HTMLCanvasElement
    cw: number
    ch: number
}
interface StillReq {
    key: string
    job: StillJob
    /** false once the button wants another still or is gone: the request is skipped */
    want: () => boolean
    /** called right after the draw, in the same task (the WebGL drawing buffer is valid only until then) */
    done: (o: StillOut) => void
}
const STILL_MAX_PX = 16e6 // largest still in device px (canvas area limits, memory)
const STILL_CACHE_PX = 8e6 // pixel budget of the still cache; a still above a quarter of it is not cached
const STILL_IDLE_MS = 1500 // the shared context is released this long after the last still
const STILL = {
    q: [] as StillReq[],
    busy: false,
    gl: null as { cv: HTMLCanvasElement; R: Renderer } | null,
    seq: 0,
    idle: null as ReturnType<typeof setTimeout> | null,
    /** no usable WebGL on this page (no context, or no fp32 fragment shaders): the CSS stand-in stays */
    dead: false,
    cache: new Map<string, StillOut>(),
    px: 0,
}
const r4 = (x: unknown) => (typeof x === "number" ? Math.round(x * 1e4) / 1e4 : x)
/** Everything the picture of a still depends on (its resolution is added to the cache key separately). */
function stillContent(j: StillJob): string {
    return [j.look.constKey, j.t, j.W, j.H, j.guard, j.scale, j.reach, j.gain, j.side, j.seed].map(r4).join("|")
}
function stillRelease() {
    if (!STILL.gl) return
    STILL.gl.R.dispose()
    STILL.gl.cv.width = STILL.gl.cv.height = 1
    STILL.gl = null
}
/** Draws the still into the shared context's canvas (uniforms and canvas span as the live renderer's first frame). */
function stillDraw(R: Renderer, cv: HTMLCanvasElement, p: Prog, j: StillJob): StillOut | null {
    const id = j.look.id
    const st = createFrameUniforms(id)
    const hu = st as unknown as { uHov: F4; uHov2: F4 }
    hu.uHov = new Float32Array(4)
    hu.uHov2 = new Float32Array(4)
    const W = j.W,
        H = j.H,
        aspect = W / H
    const fo: FrameOpts = { scale: j.scale, gain: j.gain, reach: j.reach, boost: 0, guard: j.guard, aspect, dither: 1, seed: j.seed }
    frameUniforms(id, j.t, fo, st)
    hu.uHov2[3] = st.uDither
    const so: FrameOpts = { scale: j.scale, reach: j.reach, aspect: 0 }
    const wCss = Math.min(W, canvasSpan(id, so) * H)
    // device px per CSS px: as asked, within the context's largest buffer side and the area limit
    const lim = R.maxSide()
    let s = Math.max(0.5, Math.min(j.res, lim / Math.max(wCss, 1), lim / H, Math.sqrt(STILL_MAX_PX / Math.max(wCss * H, 1))))
    for (let k = 0; k < 3; k++) {
        const pxW = Math.max(1, Math.ceil(wCss * s - 1e-4)),
            pxH = Math.max(1, Math.ceil(H * s - 1e-4))
        const cw = pxW / s
        R.draw(p, j.look, st, pxW, pxH, W, H, W - cw, s)
        const [bw, bh] = R.bufferSize()
        if (bw === pxW && bh === pxH) return { cv, cw, ch: pxH / s }
        // the browser made a smaller drawing buffer (memory): draw smaller instead of a cropped still
        if (!(bw > 0 && bh > 0)) return null
        s = Math.max(0.5, s * Math.min(bw / pxW, bh / pxH) * 0.98)
    }
    return null
}
function stillCache(key: string, o: StillOut): StillOut {
    const n = o.cv.width * o.cv.height
    if (n > STILL_CACHE_PX / 4) return o
    const c = document.createElement("canvas")
    c.width = o.cv.width
    c.height = o.cv.height
    const c2 = c.getContext("2d")
    if (!c2) return o
    c2.drawImage(o.cv, 0, 0)
    const out = { cv: c, cw: o.cw, ch: o.ch }
    STILL.cache.set(key, out)
    STILL.px += n
    for (const [k, v] of STILL.cache) {
        if (STILL.px <= STILL_CACHE_PX) break
        STILL.cache.delete(k)
        STILL.px -= v.cv.width * v.cv.height
    }
    return out
}
/** Renders one still (compile polled with timers, at most 15 s), then the next request. */
function stillRender(req: StillReq) {
    const finish = (o: StillOut | null) => {
        STILL.busy = false
        if (o && req.want()) {
            try {
                req.done(stillCache(req.key, o))
            } catch {
                // a still that cannot be shown leaves the stand-in
            }
        }
        setTimeout(stillNext, 0)
    }
    if (!STILL.gl) {
        const cv = document.createElement("canvas")
        const R = createRenderer(cv)
        if (typeof R === "string") {
            if (R !== "lost") STILL.dead = true // "lost": the GPU process restarts, the next request tries again
            return finish(null)
        }
        STILL.gl = { cv, R }
    }
    const { cv, R } = STILL.gl
    const t0 = performance.now()
    const tick = () => {
        if (!req.want()) return finish(null)
        if (R.isLost()) {
            stillRelease()
            return finish(null)
        }
        const p = R.use(req.job.look.id, -1e9 - ++STILL.seq) // a new "frame" per call: compile, link and draw in a row
        if (p === "failed") return finish(null)
        if (p === "pending") {
            if (performance.now() - t0 > 15000) return finish(null)
            setTimeout(tick, 16)
            return
        }
        let o: StillOut | null = null
        try {
            o = stillDraw(R, cv, p, req.job)
        } catch {
            o = null
        }
        finish(o)
    }
    tick()
}
function stillNext() {
    if (STILL.busy) return
    for (;;) {
        const req = STILL.q.shift()
        if (!req) {
            if (STILL.idle) clearTimeout(STILL.idle)
            STILL.idle = setTimeout(() => {
                STILL.idle = null
                if (!STILL.busy && !STILL.q.length) stillRelease()
            }, STILL_IDLE_MS)
            return
        }
        if (!req.want() || STILL.dead) continue
        const hit = STILL.cache.get(req.key)
        if (hit) {
            req.done(hit)
            continue
        }
        STILL.busy = true
        stillRender(req)
        return
    }
}
/** Queue a still. A cached one is drawn at once (inside the caller's layout effect, before the paint). */
function stillRequest(req: StillReq) {
    if (typeof document === "undefined" || STILL.dead) return
    const hit = STILL.cache.get(req.key)
    if (hit) {
        STILL.cache.delete(req.key) // most recently used last
        STILL.cache.set(req.key, hit)
        req.done(hit)
        return
    }
    if (STILL.idle) clearTimeout(STILL.idle)
    STILL.idle = null
    STILL.q.push(req)
    if (!STILL.busy) setTimeout(stillNext, 0) // a commit of many buttons queues them all first
}
const dprNow = () => (typeof window !== "undefined" && window.devicePixelRatio > 0 ? window.devicePixelRatio : 1)
/**
 * Device px per CSS px for a still of el: max(DPR, 2), at most 3, x the effective CSS scale of el (its box on screen over its
 * layout size w x h: every ancestor transform, such as Framer's canvas zoom, and its own scale), in 1/256 steps.
 */
function stillRes(el: HTMLElement, w: number, h: number): number {
    const r = el.getBoundingClientRect()
    let k = Math.max(w > 0 ? r.width / w : 0, h > 0 ? r.height / h : 0)
    if (!(k > 0) || !isFinite(k)) k = 1
    return Math.max(1 / 256, Math.round(clamp(dprNow(), 2, 3) * k * 256) / 256)
}
/**
 * The still resolution of a button, kept up to date with the canvas zoom: read after wheel, pinch (Safari gesture), key and
 * pointer-up events (debounced 150 ms), window resizes, DPR changes, size changes and once a second while on screen.
 * It changes when the needed resolution grows by more than 2 % or falls below 1 / 1.1 of the current one (zoomed out: a
 * bitmap much larger than its size on screen would be downscaled, softer and heavier); an offscreen button keeps its still.
 */
function useStillRes(rootRef: React.MutableRefObject<HTMLElement | null>, size: Size): number {
    const [res, setRes] = React.useState(0)
    const sz = React.useRef(size)
    sz.current = size
    const readRef = React.useRef<() => void>(() => {})
    React.useEffect(() => {
        const el = rootRef.current
        if (!el || typeof window === "undefined") return
        let visible = true
        let timer: ReturnType<typeof setTimeout> | null = null
        const read = () => {
            const S = sz.current
            if (!S.measured || !(S.w > 0 && S.h > 0)) return
            const r = stillRes(el, S.w, S.h)
            setRes((o) => (o > 0 && (!visible || (r <= o * 1.02 && r >= o / 1.1)) ? o : r))
        }
        readRef.current = read
        const soon = () => {
            if (timer) clearTimeout(timer)
            timer = setTimeout(() => {
                timer = null
                read()
            }, 150)
        }
        const evs = ["wheel", "gesturechange", "gestureend", "keyup", "pointerup", "resize"]
        const opt: AddEventListenerOptions = { passive: true, capture: true }
        for (const e of evs) window.addEventListener(e, soon, opt)
        let mq: MediaQueryList | null = null
        const onDpr = () => {
            if (mq) mq.removeEventListener?.("change", onDpr)
            mq = typeof window.matchMedia === "function" ? window.matchMedia(`(resolution: ${dprNow()}dppx)`) : null
            mq?.addEventListener?.("change", onDpr)
            soon()
        }
        onDpr()
        const io =
            typeof IntersectionObserver !== "undefined"
                ? new IntersectionObserver((entries) => {
                      visible = entries[entries.length - 1].isIntersecting
                      if (visible) read()
                  })
                : null
        io?.observe(el)
        const iv = setInterval(() => {
            if (visible) read()
        }, 1000)
        read()
        return () => {
            readRef.current = () => {}
            for (const e of evs) window.removeEventListener(e, soon, opt)
            mq?.removeEventListener?.("change", onDpr)
            io?.disconnect()
            clearInterval(iv)
            if (timer) clearTimeout(timer)
        }
        // eslint-disable-next-line react-hooks/exhaustive-deps
    }, [])
    React.useEffect(() => readRef.current(), [size.measured, size.w, size.h])
    return res
}

/** The still a static button shows: the live button's first frame (the look's still, the Sync seed as live). */
function stillJobOf(props: Props, look: Look, size: Size, side: Side, uid: string, res: number): StillJob {
    const effect = props.effect ?? {}
    return {
        look,
        t: SB_STATIC[look.id].stillTime,
        W: size.w,
        H: size.h,
        guard: size.guard,
        scale: clamp(numOr(effect.scale, 100), 80, 125) / 100,
        reach: clamp(numOr(effect.reach, 100), 80, 125) / 100,
        gain: clamp(numOr(effect.intensity, 100), 75, 130) / 100,
        side,
        seed: effect.sync === false ? seedOf(uid) : 0,
        res,
    }
}

/**
 * Framer canvas / export / thumbnails (v8): the CSS stand-in until the shader still is there, then the still (it fades in over
 * the stand-in; text, icon and border stay on top). No WebGL: the stand-in stays. No animation frames.
 */
function StaticButton(props: Props) {
    const uid = useCleanId()
    const rootRef = React.useRef<HTMLElement | null>(null)
    const look = useLook(props.look, useTokens(rootRef, props.colors))
    const side: Side = props.effect?.side === "left" ? "left" : "right"
    const size = useMeasure(rootRef, measureDeps(props, look), side)
    const res = useStillRes(rootRef, size)
    const view = React.useRef<HTMLCanvasElement | null>(null)
    // the still canvas exists only in the browser after the first commit (none in the server markup); ready = a still is on it
    const [client, setClient] = React.useState(false)
    const [ready, setReady] = React.useState(false)
    const shown = React.useRef("") // the look, colours, side and height of the still on the canvas ("" = none)
    useIsoLayoutEffect(() => setClient(true), [])
    const job = client && size.measured && size.w > 0 && size.h > 0 && res > 0 ? stillJobOf(props, look, size, side, uid, res) : null
    const key = job ? stillContent(job) + "|" + job.res : ""
    const vkey = job ? [look.constKey, side, r4(size.h)].join("|") : ""
    useIsoLayoutEffect(() => {
        const cv = view.current
        if (!job || !cv) return
        // another look, colour, side or height: the old still never shows over the new fill (the stand-in at once); other
        // changes keep the old still until the new one is drawn, a sharper one replaces it in place
        if (shown.current && shown.current !== vkey) {
            shown.current = ""
            cv.style.transition = "none"
            cv.style.opacity = "0"
            setReady(false)
        }
        let alive = true
        stillRequest({
            key,
            job,
            want: () => alive,
            done: (o) => {
                const c = view.current
                if (!alive || !c) return
                const c2 = c.getContext("2d")
                if (!c2) return
                // bitmap = the still's device px, CSS size = device px / its resolution: no CSS upscaling
                if (c.width !== o.cv.width) c.width = o.cv.width
                if (c.height !== o.cv.height) c.height = o.cv.height
                c2.clearRect(0, 0, c.width, c.height)
                c2.drawImage(o.cv, 0, 0)
                c.style.width = o.cw + "px"
                c.style.height = o.ch + "px"
                if (!shown.current) {
                    void getComputedStyle(c).opacity // settle at 0, then fade in (the stand-in goes once it is opaque)
                    c.style.transition = ""
                    c.style.opacity = "1"
                    setReady(true)
                }
                shown.current = vkey
            },
        })
        return () => {
            alive = false
        }
        // eslint-disable-next-line react-hooks/exhaustive-deps
    }, [key])
    const still = client ? <canvas ref={view} className="sb-gl" aria-hidden="true" /> : null
    return renderPill({ props, uid, look, size, live: ready, standIn: true, isStatic: true, rootRef, still })
}

// ---- WebGL renderer (one context per instance) ----
type GL = WebGLRenderingContext | WebGL2RenderingContext
interface UInfo {
    loc: WebGLUniformLocation
    type: number
    size: number
}
interface Prog {
    prog: WebGLProgram | null
    shaders: WebGLShader[]
    /** 0 compiling, 1 ready, 2 failed */
    state: 0 | 1 | 2
    u: Map<string, UInfo>
    constKey: string
    geo: Float64Array
    /** drawn once in this context (the first draw can build the GPU pipeline, so it counts against the frame budget) */
    drawn: boolean
    /** per preset id: the per-frame uniforms this program uses and their FrameState keys (built once, no lookups per frame) */
    fu: Map<PresetId, { us: UInfo[]; ks: string[] }>
}
interface Renderer {
    /** the program for this look, or "pending" (compiling, or this frame's GL budget is used up: poll next frame) */
    use(id: PresetId, now: number): Prog | "pending" | "failed"
    /** true when the program of this variant (family:define) is compiled and linked in this context */
    has(key: string): boolean
    draw(p: Prog, look: Look, st: FrameState, pxW: number, pxH: number, W: number, H: number, offset: number, scale: number): void
    reset(): void
    dispose(): void
    isLost(): boolean
    /** v8: the largest drawing buffer side of this context (viewport and renderbuffer limits) */
    maxSide(): number
    /** v8: the drawing buffer as the browser made it (it may give less than the canvas size under memory pressure) */
    bufferSize(): [number, number]
}

const VERT = "attribute vec2 p;\nvoid main() { gl_Position = vec4(p, 0.0, 1.0); }"
const VARIANT = {} as Record<PresetId, string>
for (const id of Object.keys(SB_PRESETS) as PresetId[]) VARIANT[id] = SB_PRESETS[id].family + ":" + SB_PRESETS[id].define
/**
 * At most one shader compile, link check or first draw per animation frame on the whole page: each can block the main
 * thread for tens of ms (WebKit with a cold shader cache), so a page of buttons starts them a frame apart, not all at once.
 * now = the rAF timestamp (the same for every callback of one frame).
 */
const GL_BUDGET = { frame: -1 }
function claimGL(now: number): boolean {
    if (GL_BUDGET.frame === now) return false
    GL_BUDGET.frame = now
    return true
}

/** A renderer, or why not: "unsupported" (no fp32 fragment shaders: CSS for good), "none" (no context), "lost" (lost at once). */
function createRenderer(canvas: HTMLCanvasElement): Renderer | "unsupported" | "none" | "lost" {
    const attrs: WebGLContextAttributes = {
        alpha: false,
        antialias: false,
        depth: false,
        stencil: false,
        premultipliedAlpha: false,
        preserveDrawingBuffer: false,
        powerPreference: "low-power",
    }
    let gl: GL | null = null
    try {
        gl = canvas.getContext("webgl2", attrs)
    } catch {
        gl = null
    }
    if (!gl) {
        try {
            gl = canvas.getContext("webgl", attrs)
        } catch {
            gl = null
        }
    }
    if (!gl) return "none"
    const g: GL = gl
    if (g.isContextLost()) return "lost" // e.g. while the GPU process restarts: try again later
    const lose = g.getExtension("WEBGL_lose_context")
    if (!supported(g)) {
        lose?.loseContext()
        return "unsupported"
    }
    let par = g.getExtension("KHR_parallel_shader_compile") as { COMPLETION_STATUS_KHR: number } | null
    let maxSide = 4096
    try {
        const vp = g.getParameter(g.MAX_VIEWPORT_DIMS) as Int32Array | null
        const rb = g.getParameter(g.MAX_RENDERBUFFER_SIZE) as number
        const m = Math.min(vp ? vp[0] : 4096, vp ? vp[1] : 4096, rb > 0 ? rb : 4096)
        if (m >= 1024) maxSide = m
    } catch {
        maxSide = 4096
    }
    const progs = new Map<string, Prog>()
    let buf: WebGLBuffer | null = null
    let current: WebGLProgram | null = null
    let gone = false
    const setup = () => {
        buf = g.createBuffer()
        g.bindBuffer(g.ARRAY_BUFFER, buf)
        g.bufferData(g.ARRAY_BUFFER, new Float32Array([-1, -1, 3, -1, -1, 3]), g.STATIC_DRAW)
        g.enableVertexAttribArray(0)
        g.vertexAttribPointer(0, 2, g.FLOAT, false, 0, 0)
    }
    setup()
    const comps = (type: number) =>
        type === g.FLOAT ? 1 : type === g.FLOAT_VEC2 ? 2 : type === g.FLOAT_VEC3 ? 3 : type === g.FLOAT_VEC4 ? 4 : 0
    const fit = (v: Float32Array, n: number) => {
        if (v.length === n) return v
        const f = new Float32Array(n)
        f.set(v.length > n ? v.subarray(0, n) : v)
        return f
    }
    /** Generic typed upload: float, vec2-4 and their arrays (uLut, uPal). */
    const put = (u: UInfo, v: number | Float32Array) => {
        if (typeof v === "number") {
            if (u.type === g.FLOAT) g.uniform1f(u.loc, v)
            return
        }
        const n = comps(u.type)
        if (!n) return
        const f = fit(v, n * u.size)
        if (n === 1) g.uniform1fv(u.loc, f)
        else if (n === 2) g.uniform2fv(u.loc, f)
        else if (n === 3) g.uniform3fv(u.loc, f)
        else g.uniform4fv(u.loc, f)
    }
    const compile = (id: PresetId): Prog => {
        const prog = g.createProgram()
        const p: Prog = { prog, shaders: [], state: 0, u: new Map(), constKey: "", geo: new Float64Array(6), drawn: false, fu: new Map() }
        if (!prog) {
            p.state = 2
            return p
        }
        const add = (type: number, src: string) => {
            const s = g.createShader(type)
            if (!s) return false
            g.shaderSource(s, src)
            g.compileShader(s)
            g.attachShader(prog, s)
            p.shaders.push(s)
            return true
        }
        if (!add(g.VERTEX_SHADER, VERT) || !add(g.FRAGMENT_SHADER, shaderSource(id))) {
            p.state = 2
            return p
        }
        g.bindAttribLocation(prog, 0, "p")
        g.linkProgram(prog) // no status query here: with KHR_parallel_shader_compile the link runs off the main thread
        return p
    }
    const finish = (p: Prog) => {
        const prog = p.prog as WebGLProgram
        if (!g.getProgramParameter(prog, g.LINK_STATUS)) {
            p.state = 2
            return
        }
        const n = g.getProgramParameter(prog, g.ACTIVE_UNIFORMS) as number
        for (let i = 0; i < n; i++) {
            const info = g.getActiveUniform(prog, i)
            if (!info) continue
            const name = info.name.replace(/\[0\]$/, "")
            const loc = g.getUniformLocation(prog, name)
            if (loc) p.u.set(name, { loc, type: info.type, size: info.size })
        }
        for (const s of p.shaders) {
            g.detachShader(prog, s)
            g.deleteShader(s)
        }
        p.shaders = []
        p.state = 1
    }
    return {
        has(key) {
            const p = progs.get(key)
            return !!p && p.state === 1
        },
        use(id, now) {
            const key = VARIANT[id] // C1 and C2 share one program
            let p = progs.get(key)
            if (!p) {
                if (!claimGL(now)) return "pending"
                p = compile(id)
                progs.set(key, p)
                if (par && p.state === 0) return "pending" // the link runs off the main thread: poll on the next frames
            }
            if (p.state === 0) {
                if (par && !g.getProgramParameter(p.prog as WebGLProgram, par.COMPLETION_STATUS_KHR)) return "pending"
                if (!claimGL(now)) return "pending"
                finish(p)
            }
            if (p.state !== 1) return "failed"
            if (!p.drawn) {
                if (!claimGL(now)) return "pending"
                p.drawn = true // the caller draws right away
            }
            return p
        },
        draw(p, look, st, pxW, pxH, W, H, offset, scale) {
            if (canvas.width !== pxW) canvas.width = pxW
            if (canvas.height !== pxH) canvas.height = pxH
            if (current !== p.prog) {
                g.useProgram(p.prog)
                current = p.prog
            }
            const G = p.geo
            if (G[0] !== pxW || G[1] !== pxH || G[2] !== W || G[3] !== H || G[4] !== offset || G[5] !== scale) {
                G[0] = pxW
                G[1] = pxH
                G[2] = W
                G[3] = H
                G[4] = offset
                G[5] = scale
                const res = p.u.get("uRes"),
                    pill = p.u.get("uPill")
                if (res) g.uniform2f(res.loc, pxW, pxH)
                if (pill) g.uniform4f(pill.loc, W, H, offset, scale)
            }
            const s = st as unknown as Record<string, number | Float32Array>
            let f = p.fu.get(look.id)
            if (!f) {
                f = { us: [], ks: [] }
                for (const k in s) {
                    const u = p.u.get(k)
                    if (u) {
                        f.us.push(u)
                        f.ks.push(k)
                    }
                }
                p.fu.set(look.id, f)
            }
            if (p.constKey !== look.constKey) {
                // look / colour change: every uniform the program declares and this look does not set (neither a preset
                // constant nor a per-frame entry) goes back to 0, as in a freshly linked program, so a shared program
                // (C1 / C2) keeps nothing of the previous look; then the look's constants, whatever their names
                const own = new Set<string>(f.ks)
                own.add("uRes")
                own.add("uPill")
                for (const [k] of look.consts) own.add(k)
                for (const [k, u] of p.u) if (!own.has(k)) put(u, new Float32Array(comps(u.type) * u.size))
                for (const [k, v] of look.consts) {
                    const u = p.u.get(k)
                    if (u) put(u, v)
                }
                p.constKey = look.constKey
            }
            for (let i = 0; i < f.us.length; i++) put(f.us[i], s[f.ks[i]])
            g.viewport(0, 0, pxW, pxH)
            g.drawArrays(g.TRIANGLES, 0, 3)
        },
        reset() {
            // after webglcontextrestored: every GL object is gone
            progs.clear()
            current = null
            par = g.getExtension("KHR_parallel_shader_compile") as { COMPLETION_STATUS_KHR: number } | null
            setup()
        },
        isLost: () => g.isContextLost(),
        maxSide: () => maxSide,
        bufferSize: () => [g.drawingBufferWidth, g.drawingBufferHeight],
        dispose() {
            // a second call (a disposed unit whose context was restored after all) only releases the context again
            if (!g.isContextLost() && !gone) {
                for (const p of progs.values()) {
                    for (const s of p.shaders) g.deleteShader(s)
                    if (p.prog) g.deleteProgram(p.prog)
                }
                if (buf) g.deleteBuffer(buf)
            }
            gone = true
            buf = null
            progs.clear()
            if (!g.isContextLost()) lose?.loseContext()
        },
    }
}

/** One WebGL context with its canvas; the pool lends it to one button at a time. */
interface GLUnit {
    canvas: HTMLCanvasElement
    R: Renderer
    owner: PoolSlot | null
    lost: boolean
    /** disposed (a late webglcontextrestored only releases the context again) */
    dead: boolean
    /** creation time (browsers evict the oldest context first) */
    born: number
    idleTimer: ReturnType<typeof setTimeout> | null
}
interface PoolSlot {
    /** the button's root: waiting buttons are served in page order */
    el: Element
    visible: () => boolean
    /** the shader variant this button needs (a unit that already has it is preferred: no compile) */
    variant: () => string
    /** the pool takes the unit away (this button is offscreen and a visible one needs a context) */
    detach: () => void
    /** a waiting button gets a unit */
    adopt: (u: GLUnit) => void
    lost: () => void
    restored: () => void
}
/**
 * Context pool. Browsers keep about 16 WebGL contexts per page and drop the oldest, and WebKit keeps counting released contexts
 * until they are garbage-collected. So the component keeps at most MAX_CONTEXTS live contexts and reuses them: an unmounted
 * button leaves its unit idle for the next one, and at the cap an offscreen button hands its unit to a visible one; otherwise
 * the newcomer shows the CSS stand-in until a unit frees up. Lost contexts do not count: a button whose context is lost and
 * not restored within LOST_MS (e.g. evicted by other WebGL on the page) disposes it and takes a new one. When one of our own
 * new contexts evicts an older one of ours, the page is at the browser's limit (other WebGL holds the rest): the cap drops to
 * the contexts still alive, so buttons do not evict each other in turn, and is raised again by one after 10, 20, 40 .. 120 s.
 * 12 keeps an overview of all eleven looks fully live and leaves 4 for other WebGL on the page.
 */
const MAX_CONTEXTS = 12
const IDLE_MS = 10000 // an idle unit (no button) is disposed after this, incl. WEBGL_lose_context
const LOST_MS = 1500 // a lost context that is not restored within this is replaced
const POOL = {
    units: new Set<GLUnit>(),
    waiting: new Set<PoolSlot>(),
    /** no usable WebGL on this page (fp16 GPU, or no context three times in a row): every button keeps the CSS stand-in */
    dead: false,
    /** failed creations in a row (backoff), and how many of them returned no context at all */
    fails: 0,
    nulls: 0,
    retry: null as ReturnType<typeof setTimeout> | null,
    /** live contexts allowed now (MAX_CONTEXTS, lower after the browser's limit was hit) */
    cap: MAX_CONTEXTS,
    lastCreate: -1e9,
    probe: null as ReturnType<typeof setTimeout> | null,
    probeMs: 5000,
}
/** One of our new contexts evicted an older one of ours: stay at the contexts still alive, try one more later. */
function limitHit(alive: number) {
    POOL.cap = Math.max(1, Math.min(POOL.cap, alive))
    POOL.probeMs = Math.min(POOL.probeMs * 2, 120000)
    if (POOL.probe) clearTimeout(POOL.probe)
    const probe = () => {
        POOL.probe = null
        if (POOL.cap >= MAX_CONTEXTS) return
        POOL.cap++
        poolWake()
        if (POOL.cap < MAX_CONTEXTS) POOL.probe = setTimeout(probe, POOL.probeMs)
    }
    POOL.probe = setTimeout(probe, POOL.probeMs)
}
/** a before b in the page (Node.DOCUMENT_POSITION_FOLLOWING = 4) */
const domOrder = (a: { el: Element }, b: { el: Element }) => (a.el === b.el ? 0 : a.el.compareDocumentPosition(b.el) & 4 ? -1 : 1)
function disposeUnit(u: GLUnit) {
    if (u.idleTimer) clearTimeout(u.idleTimer)
    u.idleTimer = null
    u.dead = true
    POOL.units.delete(u)
    u.owner = null
    u.R.dispose()
    u.canvas.remove()
}
function createUnit(): GLUnit | "unsupported" | "none" | "lost" {
    const canvas = document.createElement("canvas")
    canvas.className = "sb-gl"
    canvas.setAttribute("aria-hidden", "true")
    const R = createRenderer(canvas)
    if (typeof R === "string") return R
    const u: GLUnit = { canvas, R, owner: null, lost: false, dead: false, born: performance.now(), idleTimer: null }
    canvas.addEventListener("webglcontextlost", (e) => {
        e.preventDefault() // allows webglcontextrestored
        if (u.dead) return
        u.lost = true
        if (performance.now() - POOL.lastCreate < 500) {
            // our oldest live context, lost right after we created a new one: the browser evicted it for ours (its limit)
            let alive = 0,
                newer = false,
                older = false
            for (const v of POOL.units)
                if (v !== u && !v.R.isLost()) {
                    alive++
                    if (v.born > u.born) newer = true
                    else older = true
                }
            if (newer && !older) limitHit(alive)
        }
        u.owner?.lost()
    })
    canvas.addEventListener("webglcontextrestored", () => {
        if (u.dead) {
            u.R.dispose() // replaced meanwhile: release it again
            return
        }
        u.lost = false
        u.R.reset()
        u.owner?.restored()
    })
    return u
}
function poolAcquire(slot: PoolSlot): GLUnit | null {
    if (POOL.dead) return null
    let active = 0
    for (const u of POOL.units) {
        if (u.lost && !u.owner) disposeUnit(u) // lost while idle and never restored
        else if (!u.lost) active++
    }
    const want = slot.variant()
    const pick = (ok: (u: GLUnit) => boolean) => {
        let any: GLUnit | null = null
        for (const u of POOL.units)
            if (!u.lost && ok(u)) {
                if (u.R.has(want)) return u
                if (!any) any = u
            }
        return any
    }
    let take = pick((u) => !u.owner) // an idle unit, preferably with the variant compiled
    if (!take && active < POOL.cap && !POOL.retry) {
        const made = createUnit()
        if (typeof made === "string") {
            if (made === "unsupported" || (made === "none" && ++POOL.nulls >= 3)) {
                POOL.dead = true
                POOL.waiting.clear()
                return null
            }
            // no context right now (e.g. a GPU process restart): wait (1, 2, 4 .. 15 s), then serve the waiting buttons again
            POOL.fails++
            POOL.waiting.add(slot)
            POOL.retry = setTimeout(() => {
                POOL.retry = null
                poolWake()
            }, Math.min(1000 * 2 ** (POOL.fails - 1), 15000))
            return null
        }
        POOL.fails = POOL.nulls = 0
        POOL.lastCreate = performance.now()
        take = made
        POOL.units.add(take)
    }
    if (!take) {
        take = pick((u) => !!u.owner && !u.owner.visible()) // an offscreen button's unit
        if (take && take.owner) take.owner.detach()
    }
    if (!take) {
        POOL.waiting.add(slot)
        return null
    }
    if (take.idleTimer) clearTimeout(take.idleTimer)
    take.idleTimer = null
    POOL.waiting.delete(slot)
    take.owner = slot
    return take
}
/** The unit goes idle (its button unmounted): a waiting visible button gets it, else it is disposed after 10 s. */
function poolReturn(u: GLUnit) {
    u.owner = null
    u.canvas.remove()
    if (u.lost) {
        disposeUnit(u)
        poolWake()
        return
    }
    poolWake()
    if (!u.owner) u.idleTimer = setTimeout(() => !u.owner && disposeUnit(u), IDLE_MS)
}
/**
 * Context creation costs 3-45 ms each (the first one starts the GPU process): one start per task, never all in one, in page
 * order (so with more buttons than contexts the first ones on the page are live).
 */
interface Starter {
    el: Element
    run: () => void
}
const START_Q: Starter[] = []
let startTimer: ReturnType<typeof setTimeout> | null = null
function queueStart(s: Starter) {
    if (!START_Q.includes(s)) START_Q.push(s)
    if (!startTimer) startTimer = setTimeout(runStart, 0)
}
function runStart() {
    startTimer = null
    let k = 0
    for (let i = 1; i < START_Q.length; i++) if (domOrder(START_Q[i], START_Q[k]) < 0) k = i
    const s = START_Q.length ? START_Q.splice(k, 1)[0] : null
    if (s) s.run()
    if (START_Q.length && !startTimer) startTimer = setTimeout(runStart, 0)
}

/** A unit may be available (one went idle, or its button left the screen): serve the waiting visible buttons in page order. */
function poolWake() {
    if (!POOL.waiting.size) return
    for (const w of [...POOL.waiting].sort(domOrder)) {
        if (!w.visible()) continue
        const u = poolAcquire(w)
        if (!u) break
        w.adopt(u)
    }
}

interface LiveParams {
    look: Look
    side: Side
    speed: number
    scale: number
    gain: number
    reach: number
    boostAmt: number
    /** v6 hover effect */
    hfx: HoverEffect
    seed: number
}

/**
 * v6 hover effects inside the glow, per unit strength (Hover > Boost 100 %; the default 60 % scales every value by 0.6).
 * R = reach fraction, G = gain fraction (soft body / transfer, so cores and maxima hold), flow = extra flow speed, all x the
 * swell level s (critically damped spring, in ~0.4 s, out ~0.6 s). Follow adds the pointer: the field drifts toward its row
 * (F), the glow stretches toward it (T) and reaches further in while the pointer is further from the cap (lean). Ignite adds a
 * one-shot flare on enter (impulse response t e^-wt, peak 1 after 0.22 s, gone after ~1.2 s). A press flares every effect but
 * None a little. Reduced motion: the swell level jumps, no flare, no pointer follow.
 */
const HOVER_FX: Record<HoverEffect, { R: number; G: number; flow: number; T: number; F: number; lean: number; flR: number; flG: number; flFlow: number; press: number }> = {
    swell: { R: 0.65, G: 0.8, flow: 1.3, T: 0, F: 0, lean: 0, flR: 0, flG: 0, flFlow: 0, press: 1 },
    follow: { R: 0.12, G: 0.45, flow: 0.8, T: 1.0, F: 2.2, lean: 0.35, flR: 0, flG: 0, flFlow: 0, press: 1 },
    ignite: { R: 0.38, G: 0.55, flow: 0.8, T: 0, F: 0, lean: 0, flR: 0.65, flG: 1.8, flFlow: 2.2, press: 1 },
    none: { R: 0, G: 0, flow: 0, T: 0, F: 0, lean: 0, flR: 0, flG: 0, flFlow: 0, press: 0 },
}
const PRESS_FX = { R: 0.16, G: 0.6, flow: 0.8 }
const HOVER_KEYS: HoverEffect[] = ["swell", "follow", "ignite", "none"]
const hoverFx = (x: unknown): HoverEffect => (HOVER_KEYS.indexOf(x as HoverEffect) >= 0 ? (x as HoverEffect) : "swell")
/** Canvas span factor for the largest hover reach of an effect (the canvas keeps one size while the hover eases). */
function hoverSpan(fx: HoverEffect, amt: number): number {
    const P = HOVER_FX[fx]
    const f = (1 + amt * (P.R + P.lean + 1.1 * P.flR + 1.1 * P.press * PRESS_FX.R)) * (1 + amt * P.T)
    return f > 1 ? f + 0.02 : 1 // no hover reach (None, strength 0): exactly the v5 canvas
}
/** Pointer / focus input of one button (written by the event handlers, read by the render loop). */
interface HoverInput {
    ptr: number
    foc: number
    /** pointer position in the button box (0..1), -1 = unknown */
    x: number
    y: number
    /** pointer pressed */
    down: number
}
/** critically damped spring toward `to` (state x, v in a, index i); omega in 1/s */
function spring(a: Float64Array, i: number, to: number, w: number, dt: number) {
    a[i + 1] += (w * w * (to - a[i]) - 2 * w * a[i + 1]) * dt
    a[i] += a[i + 1] * dt
}
// HoverState layout (Float64Array): s sV f fV px pxV py pyV fl flV pr prV qf qfV qp qpV
// Flares are two critically damped stages: a kicked stage q (t e^-wt) drives the shown value (so it starts with zero slope)
const HS = { s: 0, f: 2, px: 4, py: 6, fl: 8, pr: 10, qf: 12, qp: 14, n: 16 }
const W_FLARE = 4.5,
    W2_FLARE = 9,
    W_PRESS = 6,
    W2_PRESS = 13
/** kick of the first stage that gives a peak of 1 in the second (simulated once) */
function flareKick(w: number, w2: number): number {
    const a = new Float64Array(4)
    a[1] = 1
    let peak = 0
    for (let i = 0; i < 4000; i++) {
        spring(a, 0, 0, w, 1 / 1000)
        spring(a, 2, a[0], w2, 1 / 1000)
        peak = Math.max(peak, a[2])
    }
    return 1 / peak
}
const KICK_FLARE = flareKick(W_FLARE, W2_FLARE),
    KICK_PRESS = flareKick(W_PRESS, W2_PRESS)
/**
 * One hover step: springs and impulses, then the uniforms uHov = (R, G, pointer y, pointer x_r H) and uHov2.xy = (F, T).
 * snap = jump to the targets (reduced motion, first frame). Returns the extra flow speed (0 = none); m.hBusy = still moving.
 */
function stepHover(m: Motion, hv: HoverInput, S: LiveParams, dt: number, snap: boolean, aspect: number, hov: F4, hov2: F4): number {
    const a = m.hs,
        P = HOVER_FX[S.hfx],
        amt = S.boostAmt
    const on = hv.ptr > hv.foc ? hv.ptr : hv.foc
    const ptrIn = hv.ptr > 0 && hv.x >= 0
    const fT = S.hfx === "follow" && ptrIn && !snap ? 1 : 0
    // pointer in x_r (H from the glow end; side Left: the canvas is mirrored) and pill y
    const txr = ptrIn ? (S.side === "left" ? hv.x : 1 - hv.x) * aspect : a[HS.px]
    const ty = ptrIn ? hv.y : a[HS.py]
    if (snap) {
        a.fill(0)
        a[HS.s] = on
        a[HS.px] = txr
        a[HS.py] = ty
        m.wasOn = on > 0
        m.wasDown = hv.down > 0
    } else if (dt > 0) {
        // rising edges: Ignite flares on enter / focus, every effect but None on a press
        if (on > 0 && !m.wasOn && P.flR + P.flG > 0) a[HS.qf + 1] = Math.min(a[HS.qf + 1] + KICK_FLARE, KICK_FLARE * 1.2)
        if (hv.down > 0 && !m.wasDown && P.press > 0) a[HS.qp + 1] = Math.min(a[HS.qp + 1] + KICK_PRESS, KICK_PRESS * 1.2)
        m.wasOn = on > 0
        m.wasDown = hv.down > 0
        if (a[HS.f] < 0.02 && fT > 0) {
            // follow starts where the pointer is (no sweep from the last position)
            a[HS.px] = txr
            a[HS.py] = ty
            a[HS.px + 1] = a[HS.py + 1] = 0
        }
        const n = Math.max(1, Math.ceil(dt * 120 - 1e-6)),
            h = dt / n
        for (let k = 0; k < n; k++) {
            spring(a, HS.s, on, on > a[HS.s] ? 9 : 6.5, h)
            spring(a, HS.f, fT, fT > a[HS.f] ? 8 : 6, h)
            spring(a, HS.px, txr, 11, h)
            spring(a, HS.py, ty, 11, h)
            spring(a, HS.qf, 0, W_FLARE, h)
            spring(a, HS.fl, a[HS.qf], W2_FLARE, h)
            spring(a, HS.qp, 0, W_PRESS, h)
            spring(a, HS.pr, a[HS.qp], W2_PRESS, h)
        }
        const to = [on, fT, txr, ty, 0, 0, 0, 0]
        let busy = false
        for (let i = 0; i < 8; i++) {
            const j = 2 * i
            if (Math.abs(a[j] - to[i]) < 5e-4 && Math.abs(a[j + 1]) < 5e-4) {
                a[j] = to[i]
                a[j + 1] = 0
            } else busy = true
        }
        m.hBusy = busy
    }
    if (snap) m.hBusy = false
    const s = Math.min(Math.max(a[HS.s], 0), 1),
        f = Math.min(Math.max(a[HS.f], 0), 1),
        fl = Math.max(a[HS.fl], 0),
        pr = Math.max(a[HS.pr], 0)
    const xr = a[HS.px]
    const lean = Math.min(Math.max((xr - 0.6) / 1.8, 0), 1)
    const leanS = lean * lean * (3 - 2 * lean)
    hov[0] = amt * (P.R * s + P.lean * f * leanS + P.flR * fl + P.press * PRESS_FX.R * pr)
    hov[1] = amt * (P.G * s + P.flG * fl + P.press * PRESS_FX.G * pr)
    hov[2] = a[HS.py]
    hov[3] = xr
    hov2[0] = amt * P.F * f
    hov2[1] = amt * P.T * f
    m.boost = s
    return amt * (P.flow * s + P.flFlow * fl + P.press * PRESS_FX.flow * pr)
}

/**
 * Shared flow clock for Sync = Yes. It starts with the first frame of the first button on the page (not at module load: a
 * page that mounts its buttons later, as Framer's preview does, would otherwise open on a frame far from the still the CSS
 * stand-in shows) and restarts when no button is running.
 */
const SYNC = { origin: 0, running: 0 }
/** Time constant of the control easing (speed, scale, intensity, reach, guard): about 300 ms to settle. */
const EASE_TAU = 0.075

/**
 * Motion state of one button. It lives in a ref, so it survives a re-run of the setup effect (the root tag changes when a link
 * or click handler is added or removed): the flow continues where it was instead of restarting at the still.
 */
interface Motion {
    /** false until the first frame was drawn: the first frame uses the controls as they are (no easing from defaults) */
    started: boolean
    /** flow time in s (integrated, so a speed change never jumps the phase) */
    t: number
    /** eased speed, scale, gain, reach, guard */
    sp: number
    sc: number
    ga: number
    re: number
    gd: number
    /** speed the sync target was anchored with (-1 = frozen / not anchored) and its offset */
    spT: number
    off: number
    /** test clock only: hover extra time, as in v3 */
    hx: number
    /** hover level s (0..1, for the test trace) and the extra flow speed of the hover (0 = none) */
    boost: number
    flow: number
    /** v6 hover springs (HS layout), edge detection, still moving */
    hs: Float64Array
    wasOn: boolean
    wasDown: boolean
    hBusy: boolean
    last: number
    counted: boolean
    /** the button was visible at the last setup (a tag change restarts the context at once, no wait for the observer) */
    visible: boolean
}
const newMotion = (): Motion => ({
    started: false, t: 0, sp: 0, sc: 1, ga: 1, re: 1, gd: 0, spT: -1, off: 0, hx: 0, boost: 0, flow: 0, hs: new Float64Array(HS.n),
    wasOn: false, wasDown: false, hBusy: false, last: 0, counted: false, visible: false,
})

/** Browser: WebGL glow on the right (or left) end, CSS stand-in or plain fill until the first frame. */
function LiveButton(props: Props) {
    const uid = useCleanId()
    const rootRef = React.useRef<HTMLElement | null>(null)
    const look = useLook(props.look, useTokens(rootRef, props.colors))
    const [live, setLive] = React.useState(false)
    // the stand-in is fitted to the look at its still with Sync = Yes; with Sync = No (own variation per button) the first
    // frame cannot match it, so the plain fill shows until then and the glow fades in from it (unless WebGL takes too long)
    const [forceFb, setForceFb] = React.useState(false)
    const geom = React.useRef({ w: 0, h: 0, guard: 0 })
    const hoverRef = React.useRef<HoverInput>({ ptr: 0, foc: 0, x: -1, y: -1, down: 0 })
    const kick = React.useRef<() => void>(() => {})
    const now0 = React.useRef<() => void>(() => {})
    const motion = React.useRef<Motion | null>(null)
    if (!motion.current) motion.current = newMotion()
    const kind = tagKindOf(props)
    const effect = props.effect ?? {}
    const side: Side = effect.side === "left" ? "left" : "right"
    const seed = effect.sync === false ? seedOf(uid) : 0
    const standIn = seed === 0 || forceFb
    const params = React.useRef<LiveParams | null>(null)
    const prevKey = React.useRef("")

    // latest values for the render loop (no re-render needed). A new look, colour or side is drawn before this commit is
    // painted (or the canvas hides at once), so the new fill never shows next to a frame of the old look.
    useIsoLayoutEffect(() => {
        params.current = {
            look,
            side,
            speed: clamp(numOr(effect.speed, 100), 0, 300) / 100,
            scale: clamp(numOr(effect.scale, 100), 80, 125) / 100,
            gain: clamp(numOr(effect.intensity, 100), 75, 130) / 100,
            reach: clamp(numOr(effect.reach, 100), 80, 125) / 100,
            boostAmt: clamp(numOr(props.hover?.boost, 60), 0, 100) / 100,
            hfx: hoverFx(props.hover?.effect),
            seed,
        }
        const key = look.constKey + "|" + side + "|" + seed
        if (key !== prevKey.current) {
            prevKey.current = key
            now0.current()
        } else kick.current()
    })

    const size = useMeasure(rootRef, measureDeps(props, look), side, (g) => {
        const o = geom.current
        const resized = o.w !== g.w || o.h !== g.h
        geom.current = g
        if (resized) now0.current() // the canvas must cover the new size in this very paint
        else kick.current()
    })

    useIsoLayoutEffect(() => {
        const root = rootRef.current
        const host = root ? root.querySelector<HTMLElement>(".sb-pill") : null
        const fb = host ? host.querySelector<HTMLElement>(".sb-fb") : null
        const m = motion.current as Motion
        if (!root || !host) return
        const mq = typeof window.matchMedia === "function" ? window.matchMedia("(prefers-reduced-motion: reduce)") : null
        let reduce = !!mq && mq.matches
        let unit: GLUnit | null = null
        let lost = false
        let raf = 0
        let visible = typeof IntersectionObserver === "undefined" || m.visible
        let liveNow = false
        let failed = false
        let shownKey = "" // the look (incl. colours) whose frame is on the canvas
        let instant = false // the next showLive(true) without a fade (tag change)
        let st: FrameState | null = null
        let stId = ""
        let lostTimer: ReturnType<typeof setTimeout> | null = null
        let retryTimer: ReturnType<typeof setTimeout> | null = null
        let fbTimer: ReturnType<typeof setTimeout> | null = null
        const losses: number[] = [] // replaced lost contexts, last 30 s
        // the options objects are reused every frame (no allocation per frame)
        const fo: FrameOpts = { scale: 1, gain: 1, reach: 1, boost: 0, guard: 0, aspect: 1, dither: 1, seed: 0 }
        const so: FrameOpts = { scale: 1, reach: 1, aspect: 1 }
        const view = { cssW: -1, cssH: -1 }

        const fbShow = (on: boolean, instant: boolean) => {
            if (!fb) return
            fb.style.transition = instant ? "none" : on ? "opacity .3s linear" : "opacity 0s linear .4s"
            fb.style.opacity = on ? "1" : "0"
        }
        /** the stand-in may show although it cannot match (no WebGL, lost, or WebGL takes too long) */
        const forceStandIn = () => {
            if (fbTimer) clearTimeout(fbTimer)
            fbTimer = null
            const p = params.current
            if (!liveNow && p && p.seed !== 0) fbShow(true, false)
            setForceFb(true)
        }
        /** canvas and stand-in opacity; instant = no fade (a look switch must never show the old look over the new fill) */
        const showLive = (v: boolean, instant = false) => {
            if (liveNow === v) return // setLive only on change
            liveNow = v
            if (unit) {
                unit.canvas.style.transition = instant ? "none" : ""
                unit.canvas.style.opacity = v ? "1" : "0"
            }
            // the stand-in right away, not one React commit later (same values as the render)
            const p = params.current
            if (v) fbShow(false, false)
            else if (!p || p.seed === 0 || failed || lost) fbShow(true, true)
            if (!v && (failed || lost)) setForceFb(true)
            setLive(v)
        }
        const uncount = () => {
            if (m.counted) SYNC.running = Math.max(0, SYNC.running - 1)
            m.counted = false
        }
        const stop = () => {
            if (raf) cancelAnimationFrame(raf)
            raf = 0
            m.last = 0
        }
        const replaceLost = () => {
            // lost and not restored (e.g. evicted by other WebGL on the page): dispose it, take a new one
            lostTimer = null
            const u = unit
            if (!u || !lost) return
            losses.push(performance.now())
            slot.detach()
            disposeUnit(u)
            poolWake()
            if (visible) queueStart(starter)
        }
        const slot: PoolSlot = {
            el: root,
            visible: () => visible,
            variant: () => (params.current ? VARIANT[params.current.look.id] : ""),
            detach: () => {
                stop()
                showLive(false)
                if (unit) unit.canvas.remove()
                unit = null
                lost = false
                uncount()
            },
            adopt: (u) => {
                unit = u
                lost = false
                liveNow = false
                shownKey = ""
                view.cssW = view.cssH = -1
                u.canvas.style.transition = m.started ? "none" : ""
                u.canvas.style.opacity = "0"
                host.appendChild(u.canvas)
                // tag change of a running button: the flow continues on the same frame, shown at once (no fade)
                instant = m.started
                const ok = m.started && drawSync()
                instant = false
                if (ok) return
                // settle the style at opacity 0 now: a reused context draws in the very next frame, and without a style
                // pass in between the canvas would jump to 1 instead of fading in
                void getComputedStyle(u.canvas).opacity
                kickNow()
            },
            lost: () => {
                lost = true
                stop()
                showLive(false)
                uncount()
                if (lostTimer) clearTimeout(lostTimer)
                lostTimer = setTimeout(replaceLost, LOST_MS)
            },
            restored: () => {
                lost = false
                if (lostTimer) clearTimeout(lostTimer)
                lostTimer = null
                shownKey = ""
                kickNow()
            },
        }
        const start = () => {
            if (!visible || unit) return
            const now = performance.now()
            while (losses.length && now - losses[0] > 30000) losses.shift()
            if (losses.length >= 3) {
                // replaced three times in 30 s (other WebGL keeps evicting it): keep the stand-in for a while, no ping-pong
                forceStandIn()
                if (!retryTimer)
                    retryTimer = setTimeout(() => {
                        retryTimer = null
                        if (visible && !unit) queueStart(starter)
                    }, losses[0] + 30000 - now + 20)
                return
            }
            const u = poolAcquire(slot) // the context is created when a button first shows
            if (u) slot.adopt(u)
            else if (POOL.dead) {
                failed = true
                forceStandIn()
            }
        }
        const starter: Starter = {
            el: root,
            run: () => {
                start()
                kickNow()
            },
        }

        /**
         * One frame. advance = false: a synchronous redraw inside a layout effect (prop or size change) that does not move the
         * clock; it returns whether a frame was drawn.
         */
        const frame = (now: number, advance: boolean): boolean => {
            const u = unit,
                S = params.current,
                G = geom.current
            if (!u || lost || !S) {
                m.last = 0
                return false
            }
            const r = u.R,
                cv = u.canvas
            let dt = 0
            if (advance) {
                dt = m.last ? clamp((now - m.last) / 1000, 1 / 240, 1 / 20) : 1 / 60
                m.last = now
            }
            if (!st || stId !== S.look.id) {
                st = createFrameUniforms(S.look.id)
                stId = S.look.id
                const sx = st as unknown as Record<string, F4>
                sx.uHov = new Float32Array(4)
                sx.uHov2 = new Float32Array(4)
            }
            const hu = st as unknown as { uHov: F4; uHov2: F4 }
            // v6 hover: springs + pointer, the uniforms uHov / uHov2.xy (reduced motion or the first frame: the target at once)
            m.flow = stepHover(m, hoverRef.current, S, dt, reduce || !m.started, G.h > 0 ? G.w / G.h : 1, hu.uHov, hu.uHov2)
            if (!(G.w > 0 && G.h > 0)) return false
            const id = S.look.id
            const lk = S.look.constKey
            if (!advance && !r.has(VARIANT[id])) {
                // not compiled in this context yet: no compile inside a layout effect; the new look's stand-in (or its plain
                // fill) at once, the loop compiles it
                if (liveNow && shownKey !== lk) showLive(false, true)
                return false
            }
            const p = r.use(id, advance ? now : -1 - now)
            if (p === "pending") {
                if (liveNow && shownKey !== lk) showLive(false, true) // look switch: the stand-in of the new look meanwhile
                return false
            }
            if (p === "failed") {
                failed = true
                showLive(false)
                return false
            }
            // controls: the first frame takes them as they are, later changes ease (~300 ms), reduced motion jumps
            const k = !m.started || reduce ? 1 : 1 - Math.exp(-dt / EASE_TAU)
            const ease = (x: number, to: number) => {
                const y = x + (to - x) * k
                return Math.abs(to - y) < 1e-4 ? to : y
            }
            m.sp = ease(m.sp, S.speed)
            m.sc = ease(m.sc, S.scale)
            m.ga = ease(m.ga, S.gain)
            m.re = ease(m.re, S.reach)
            m.gd = ease(m.gd, G.guard)
            const still = SB_STATIC[id].stillTime
            const tc = (globalThis as { __SB_TEST_CLOCK?: unknown }).__SB_TEST_CLOCK // TEST ONLY
            const frozen = reduce || (S.speed <= 0 && m.sp <= 0)
            const fresh = !m.started
            if (fresh) {
                // every button opens on the still the CSS stand-in shows
                m.t = still
                m.off = 0
                m.spT = S.speed > 0 ? S.speed : -1
                if (!SYNC.running) SYNC.origin = now
            }
            const clock = (now - SYNC.origin) / 1000
            if (typeof tc === "number") {
                // TEST ONLY (v3 timing): t = still + test clock x speed + hover extra time, paid back with Sync = Yes
                if (!frozen && dt > 0) {
                    m.hx += dt * m.flow * S.speed
                    if (S.seed === 0 && m.flow < 0.01 && m.hx > 0) {
                        m.hx -= dt * Math.min(m.hx / 6, 0.1 * S.speed)
                        if (m.hx < 1e-4) m.hx = 0
                    }
                }
                m.t = frozen ? still : still + tc * S.speed + m.hx
            } else if (reduce) m.t = still
            else {
                // Sync target: still + clock x speed + offset; a speed change moves the offset, so the target stays continuous
                if (S.speed > 0) {
                    if (m.spT > 0 && m.spT !== S.speed) m.off += clock * (m.spT - S.speed)
                    else if (m.spT <= 0) m.off = m.t - still - clock * S.speed // from a stop: anchored where the flow stands
                    m.spT = S.speed
                } else m.spT = -1
                if (dt > 0 && m.sp > 0 && !fresh) {
                    let rate = m.sp * (1 + m.flow) // hover: faster flow, never a jump
                    if (S.seed === 0 && S.speed > 0 && m.flow < 0.01) {
                        // Sync: drift into the shared field (at most 10 % faster or slower), e.g. after a hover or a late start
                        const d = still + clock * S.speed + m.off - m.t
                        rate += clamp(d / 6, -0.1, 0.1) * m.sp
                    }
                    m.t += dt * rate
                }
            }
            const W = G.w,
                H = G.h,
                aspect = W / H
            fo.scale = m.sc
            fo.gain = m.ga
            fo.reach = m.re
            fo.boost = 0 // v6: the hover lives in uHov / uHov2 (the port's uBoost is not declared by the shader)
            fo.guard = m.gd
            fo.aspect = aspect
            fo.seed = S.seed
            frameUniforms(id, m.t, fo, st)
            hu.uHov2[3] = st.uDither // the dither amplitude lives in uHov2.w since v6
            so.scale = m.sc
            so.reach = m.re
            so.aspect = 0
            // at rest the canvas has the v5 size (the same pixels); while a hover is on or easing it covers the largest hover
            // reach of the effect (one size for the whole hover, switched in the frame that draws it), but never the part
            // left of the text guard (the glow is exactly the fill there; the left cap's antialiased edge stays CSS)
            const hovering = (hoverRef.current.ptr > 0 || hoverRef.current.foc > 0 || m.hBusy) && S.boostAmt > 0
            const span = canvasSpan(id, so) * (hovering ? hoverSpan(S.hfx, S.boostAmt) : 1)
            const wCss = hovering ? Math.min(W, span * H, Math.max(W - Math.max(m.gd, GUARD_MIN) * H, canvasSpan(id, so) * H)) : Math.min(W, span * H)
            const dpr = typeof window.devicePixelRatio === "number" && window.devicePixelRatio > 0 ? window.devicePixelRatio : 1
            const s = clamp(Math.min(dpr, 240 / H), 0.5, 2)
            const pxW = Math.max(1, Math.ceil(wCss * s - 1e-4)),
                pxH = Math.max(1, Math.ceil(H * s - 1e-4))
            const cw = pxW / s,
                ch = pxH / s
            if (cw !== view.cssW) {
                view.cssW = cw
                cv.style.width = cw + "px"
            }
            if (ch !== view.cssH) {
                view.cssH = ch
                cv.style.height = ch + "px"
            }
            r.draw(p, S.look, st, pxW, pxH, W, H, W - cw, s)
            const tr = (globalThis as { __SB_TEST_TRACE?: unknown }).__SB_TEST_TRACE // TEST ONLY
            if (Array.isArray(tr))
                tr.push({ uid, now, advance, t: m.t, sp: m.sp, sc: m.sc, ga: m.ga, re: m.re, gd: m.gd, boost: m.boost, flow: m.flow, hov: Array.from(hu.uHov), hov2: Array.from(hu.uHov2), key: lk, first: !m.started })
            if (!m.started) {
                m.started = true
                if (fbTimer) clearTimeout(fbTimer)
                fbTimer = null
            }
            if (!m.counted) {
                m.counted = true
                SYNC.running++
            }
            const switched = liveNow && shownKey !== lk
            shownKey = lk
            showLive(true, switched || instant)
            return true
        }
        const loop = (now: number) => {
            raf = 0
            const drawn = frame(now, true)
            const S = params.current
            const G0 = geom.current
            // compiling, or this frame's GL budget is used: poll next frame (an unmeasured button waits for its measurement)
            let again = !drawn && !!unit && !lost && !failed && G0.w > 0 && G0.h > 0
            if (drawn && S) {
                const G = geom.current
                const moving = !reduce && (S.speed > 0 || m.sp > 0)
                const easing = m.sp !== S.speed || m.sc !== S.scale || m.ga !== S.gain || m.re !== S.reach || m.gd !== G.guard
                again = moving || easing || m.hBusy
            }
            if (again && visible && !document.hidden) raf = requestAnimationFrame(loop)
            else m.last = 0
        }
        const kickNow = () => {
            if (!raf && visible && !document.hidden && unit && !lost) raf = requestAnimationFrame(loop)
        }
        /** draw now (layout effect: before the paint), then let the loop continue */
        const drawSync = (): boolean => {
            if (!unit || lost || !visible) return false
            const ok = frame(typeof performance !== "undefined" ? performance.now() : 0, false)
            kickNow()
            return ok
        }
        kick.current = kickNow
        now0.current = () => {
            drawSync()
        }

        const io =
            typeof IntersectionObserver !== "undefined"
                ? new IntersectionObserver((entries) => {
                      visible = entries[entries.length - 1].isIntersecting
                      m.visible = visible
                      if (visible) {
                          if (unit) kickNow() // a lost unit is replaced by its timer
                          else queueStart(starter)
                      } else {
                          m.last = 0
                          poolWake() // a visible button may be waiting for this unit
                      }
                  })
                : null
        if (io) io.observe(root)
        // a tag change of a running button: take a context back at once (usually the one it just returned) and go on drawing
        if (m.started && visible) start()
        else if (!io) queueStart(starter)
        if (!liveNow) setLive(false) // a tag change that could not go on at once: the stand-in (or the fill) meanwhile
        // Sync = No: the plain fill until the first frame; if WebGL has not shown within 1.5 s, the stand-in after all
        if (!liveNow && seed !== 0 && !m.started) fbTimer = setTimeout(forceStandIn, 1500)
        if (!liveNow && fb) {
            const p = params.current
            if (p && p.seed !== 0 && !m.started) fbShow(false, true)
        }
        const onVis = () => {
            m.last = 0
            kickNow()
        }
        document.addEventListener("visibilitychange", onVis)
        const onMq = () => {
            reduce = !!mq && mq.matches
            kickNow()
        }
        if (mq) {
            if (typeof mq.addEventListener === "function") mq.addEventListener("change", onMq)
            else mq.addListener(onMq)
        }
        kickNow()
        return () => {
            kick.current = () => {}
            now0.current = () => {}
            io?.disconnect()
            document.removeEventListener("visibilitychange", onVis)
            if (mq) {
                if (typeof mq.removeEventListener === "function") mq.removeEventListener("change", onMq)
                else mq.removeListener(onMq)
            }
            m.visible = visible
            visible = false
            stop()
            if (lostTimer) clearTimeout(lostTimer)
            if (retryTimer) clearTimeout(retryTimer)
            if (fbTimer) clearTimeout(fbTimer)
            lostTimer = retryTimer = fbTimer = null
            const qi = START_Q.indexOf(starter)
            if (qi >= 0) START_Q.splice(qi, 1)
            POOL.waiting.delete(slot)
            const u = unit
            unit = null
            uncount()
            if (u) poolReturn(u) // idle for the next button (remounts, page changes), disposed after IDLE_MS
        }
        // eslint-disable-next-line react-hooks/exhaustive-deps
    }, [kind])

    const onHover = React.useCallback((k: "ptr" | "foc" | "move" | "down", v: number, x?: number, y?: number) => {
        const hv = hoverRef.current
        if (typeof x === "number" && typeof y === "number") {
            hv.x = clamp(x, 0, 1)
            hv.y = clamp(y, 0, 1)
        }
        if (k === "move") {
            // only Follow redraws on a move (the other effects ignore the position)
            if (params.current?.hfx === "follow") kick.current()
            return
        }
        hv[k] = v
        if (k === "ptr" && !v) hv.x = hv.y = -1
        kick.current()
    }, [])

    return renderPill({ props, uid, look, size, live, standIn, isStatic: false, rootRef, onHover })
}

